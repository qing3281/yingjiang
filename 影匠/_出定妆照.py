def 读角色卡(戏):
    """兜底：从 `02-九宫格.md` 的「角色卡」（或「人物」）那一节抠 `{角色: (定位, 长相串)}`。

    ★ 为什么要有这条（2026-10-15）：上面那张「## 角色文字锚点串」表是**我手写的旧几部戏**
      才有的；四步编剧流程跑出来的新戏（楚子航就是）根本没有这张表，
      于是 `读锚点()` 回 `{}`，工具直接报「找不到表」退出 ——
      而 `02-九宫格.md` 里**明明有人物长相**，只是换了个写法：

          ## 角色卡
          - 楚子航：二十一岁，卡塞尔学院的学生…

      少这条路 = 新戏永远出不了定妆照，而报错长得像「这部戏没写人物」。
    """
    路 = os.path.join(根, "作品", 戏, "02-九宫格.md")
    if not os.path.isfile(路):
        return {}
    import io
    文 = io.open(路, encoding="utf-8").read()
    出 = {}
    在卡里 = False
    for 行 in 文.splitlines():
        s = 行.strip()
        m0 = re.match(r"^#{2,3}\s*(.+?)\s*$", s)
        if m0:
            在卡里 = ("角色" in m0.group(1)) or ("人物" in m0.group(1))
            continue
        if not 在卡里:
            continue
        m = re.match(r"^-\s*\*{0,2}([^\s：:*]{1,10})\*{0,2}\s*[：:]\s*(.+)$", s)
        if not m:
            continue
        名, 串 = m.group(1).strip(), m.group(2).strip()
        if 名 and 串 and 名 not in 出:
            出[名] = ("（02-九宫格.md 的角色卡）", 串)
    return 出


def 读锚点(戏):
    """从 `01-节拍拆解.md` 的「## 角色文字锚点串」表抠 `{角色: (定位, 锚点串)}`。
    没有那张表就退回 `读角色卡()`（新戏走这条）。

    表长这样（分隔符是 `|`，第二列是定位，第三列是锚点串）：

        | 角色 | 定位 | 锚点串（发 / 眼 / 脸 / 手 / 服 / 脚，共 6 项） |
        |---|---|---|
        | **陈老根** | 青云宗外门扫了四十年地的老杂役 · 六十八岁 · 主角 | 全白的头发稀稀的，…… |
    """
    路 = os.path.join(根, "作品", 戏, "01-节拍拆解.md")
    if not os.path.isfile(路):
        return {}
    import io
    文 = io.open(路, encoding="utf-8").read()
    m = re.search(r"^##\s*角色文字锚点串.*?$(.*?)(?=^##\s|\Z)", 文, re.S | re.M)
    if not m:
        return 读角色卡(戏)
    出 = {}
    for 行 in m.group(1).splitlines():
        行 = 行.strip()
        if not 行.startswith("|") or set(行) <= set("|-: "):
            continue
        列 = [c.strip() for c in 行.strip("|").split("|")]
        if len(列) < 3 or 列[0] in ("角色", ""):
            continue
        名 = re.sub(r"\*\*", "", 列[0]).strip()
        if not 名 or 名.startswith("角色"):
            continue
        出[名] = (列[1], 列[2])
    return 出


def 造词(名, 定位, 锚点串):
    """定妆照提示词：把锚点串当「长相说明书」，外面套影棚拍法。"""
    # ★ 定妆照专用改写：锚点里有些说法，在「影棚平光正面像」这种拍法下会被模型画歪。
    #   **只影响这一张定妆照，不动 `01-节拍拆解.md`**（那份是喂给每一格首帧的）。
    #   2026-10-15 实测：陈老根那版「眼下两片青黑的眼袋」被画成了两块黑眼圈妆，
    #   「围裙（颜色是灰的，绝不是白色）」照样被画成米白 —— 否定写法没用。
    for 旧, 新 in 改词.get(名, []):
        锚点串 = 锚点串.replace(旧, 新)
    # 四个人共用的壳
    壳首 = ("角色定妆照，一张图里并排放两个视角：左边是正面半身像（从头顶到胸口），"
            "右边是正面全身像（从头顶到脚底）。两个视角是**同一个人**，"
            "站姿端正、双手自然垂在身体两侧、面朝镜头、表情平静中性。"
            "背景是均匀的中性灰，没有场景、没有道具、没有文字。"
            "影棚平光，服装和皮肤质感清楚。")
    # 「内门执事」在分镜里没做锚点串，只有四项
    壳尾 = ("写实电影质感，胶片颗粒，平光不打轮廓光，不要美颜。")
    return f"{壳首}{名}，{定位}。他的长相和穿着，逐项如下：{锚点串}{壳尾}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("戏")
    ap.add_argument("--角", default="", help="只出这些角色，逗号分隔；默认全部")
    ap.add_argument("--端点", default="本机", choices=["本机", "远端"])
    ap.add_argument("--种子偏移", type=int, default=0)
    ap.add_argument("--宽", type=int, default=1024)
    ap.add_argument("--高", type=int, default=1024)
    参 = ap.parse_args()

    引擎.换端点(参.端点)
    在 = 引擎.在线()
    print(f"  端点 {在.get('端点')}　在线={在.get('在线')}　{在.get('显卡','')}")
    if not 在.get("在线"):
        print(f"  ✗ {参.端点} 不在线：{在.get('错')}")
        return 2

    锚 = 读锚点(参.戏)
    if not 锚:
        print(f"  ✗ 作品\\{参.戏} 里找不到人物长相：`01-节拍拆解.md` 没有「## 角色文字锚点串」表，"
              f"`02-九宫格.md` 也没有「## 角色卡」那一节")
        return 1

    要 = [x.strip() for x in 参.角.split(",") if x.strip()] or list(锚)
    出目录 = os.path.join(根, "作品", 参.戏, "_定妆照")
    os.makedirs(出目录, exist_ok=True)

    print(f"  {参.戏}：{len(锚)} 个角色　出 {len(要)} 张")
    ok = 0
    for i, 名 in enumerate(要):
        if 名 not in 锚:
            print(f"    ✗ {名}：锚点表里没有")
            continue
        定位, 串 = 锚[名]
        词 = 造词(名, 定位, 串)
        t = time.time()
        try:
            r = 导演.开镜(
                词,
                角色=[],                      # ★ 关键：别让它 auto 拼全部角色
                种子=种子 + 参.种子偏移 + i * 1009,
                宽=参.宽, 高=参.高,
                文件名=f"定妆_{名}",
            )
        except Exception as e:
            print(f"    ✗ {名}：{type(e).__name__}: {e}")
            continue
        路 = r.get("路", "")
        if 路 and os.path.isfile(路):
            落 = os.path.join(出目录, f"{名}.png")
            import shutil
            shutil.move(路, 落)
            大小 = os.path.getsize(落) / 1024
            print(f"    ✓ {名 }  {time.time()-t:.1f} 秒  {大小:,.0f} KB  → _定妆照\\{名}.png")
            ok += 1
        else:
            print(f"    ✗ {名}：没有产出文件")

    print(f"\n  ✓ {ok}/{len(要)} 张 → {出目录}")
    return 0 if ok else 2


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
