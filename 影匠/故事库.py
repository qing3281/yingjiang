def 全部():
    """所有套路键"""
    return list(套路表.keys())


def 取(键):
    """取一条；支持中文名。给空或给不认识的就回 None（调用方自己决定要不要兜底）"""
    if not 键:
        return None
    if 键 in 套路表:
        return 套路表[键]
    for k, v in 套路表.items():
        if v["中文"] == 键:
            return v
    return None


def 挑(题材="", 分钟=1.5, 人数=2):
    """
    按题材/时长/人数挑一条最合适的。**打分挑，不是硬编 if**。

    返回 (键, 为什么挑它)。挑不出来就回 ("", 原因)。
    """
    题 = (题材 or "").strip()
    候选 = []
    for k, v in 套路表.items():
        s = 0
        理 = []
        if 分钟 <= 1.0 and v["几拍"] <= 5:
            s += 2; 理.append("1 分钟内它拍数够短")
        if 人数 <= 2 and k in ("单场景闭环", "两难", "误会", "最后一件事"):
            s += 2; 理.append("两个人就能撑起来")
        if 人数 >= 3 and k in ("循环", "起承转合", "追赶"):
            s += 1; 理.append("人多它才热闹")
        for 词 in ("打", "跑", "追", "逃", "枪", "斗"):
            if 词 in 题 and k == "追赶":
                s += 4; 理.append("题材是动作")
        for 词 in ("老人", "师", "收摊", "退休", "走", "别", "最后"):
            if 词 in 题 and k == "最后一件事":
                s += 4; 理.append("题材是收尾/离别")
        for 词 in ("误会", "解释", "以为"):
            if 词 in 题 and k == "误会":
                s += 4; 理.append("题材本身就是误会")
        for 词 in ("选", "两难", "还是"):
            if 词 in 题 and k == "两难":
                s += 4; 理.append("题材本身就是选择")
        if not 题 and k in ("单场景闭环", "起承转合"):
            s += 3; 理.append("没给题材，挑最稳的通用结构")
        候选.append((s, k, "；".join(理) or "通用"))
    候选.sort(key=lambda x: (-x[0], x[1]))
    if not 候选 or 候选[0][0] <= 0:
        return "", "一条都对不上"
    return 候选[0][1], 候选[0][2]


def 拼(键, 一句话=""):
    """
    把一条套路拼成能直接塞进提示词的一段。

    ★ 只出骨架，不出内容。一句话只是给模型一个方向，不是让它照抄。
    """
    v = 取(键)
    if v is None:
        return ""
    行 = ["【这一部用这个结构：%s —— 共 %d 拍】" % (v["中文"], v["几拍"])]
    if 一句话:
        行.append("故事方向是：「%s」。**这只是方向，具体人物、地点、做什么由你定。**" % 一句话)
    行.append("")
    行.append("每一拍必须让观众看见一件**上一拍没有的事**。拍与拍之间靠「变化」分开，不靠台词：")
    for x in v["骨架"]:
        行.append("  " + x)
    行.append("")
    行.append("★ 这个结构的戏眼在第 %s 拍，**这一拍写砸了整部片子就白拍**。" % v["反转点"].split(" ")[0])
    行.append("★ 这个结构最常见的砸法：%s —— 不许这么写。" % v["常见失败"])
    return "\n".join(行)


def 打印全部():
    print("\n%-14s %-4s %s" % ("键", "拍", "适合"))
    print("-" * 78)
    for k, v in 套路表.items():
        print("%-14s %-4d %s" % (k, v["几拍"], v["适合"]))
    print("\n共 %d 条\n" % len(套路表))


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 2 and sys.argv[1] == "拼":
        print(拼(sys.argv[2], " ".join(sys.argv[3:])))
    elif len(sys.argv) > 1 and sys.argv[1] == "挑":
        print(挑(" ".join(sys.argv[2:])))
    else:
        打印全部()

