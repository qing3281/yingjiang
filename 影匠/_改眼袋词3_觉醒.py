# -*- coding: utf-8 -*-
"""第三轮改眼袋 —— 把「否定句」和「颜色词」全拿掉。

前两轮改完，格2 的特写里眼下仍有一片灰蓝，看着像淤青。原因有两个：

1. **否定句会把那个东西拉进来**。原话写「（是年纪大了皮松出来的袋，
   不是黑眼圈、不是淤青、不是伤）」—— 扩散模型不吃否定，「黑眼圈 / 淤青 / 伤」
   这几个词本身就进了条件，画出来才怪。
2. **颜色词是命令**。「青灰色眼袋」= 画一片青灰。「眼窝深陷」+「压进阴影里」
   = 把眼窝涂暗。

改成**只说是什么**，而且把「跟皮肤同色」写死 —— 没给灰蓝色留位置。
"""
import io
import os

根 = os.path.dirname(os.path.abspath(__file__))
分镜 = os.path.join(根, "作品", "觉醒", "02-九宫格.md")
故事 = os.path.join(根, "作品", "觉醒", "00-故事.md")

对表 = [
    # ① 眼袋本体：去掉否定句 + 去掉颜色词，改说「跟皮肤同色」
    ("眼窝深陷，眼下只有两道老年人常见的、浅浅的青灰色眼袋"
     "（是年纪大了皮松出来的袋，不是黑眼圈、不是淤青、不是伤），左边眼珠比右边清亮一点",
     "眼窝略深，眼下是两道跟皮肤同色的浅纹，那一片皮肤的颜色和脸上别处一样，"
     "左边眼珠比右边清亮一点"),
    # ② 光色里的「陷进阴影」也是命令
    ("让眼窝整个陷进阴影里", "眼窝里只落一点很淡的阴影"),
    ("眼窝没进阴影里，而不是涂黑", "眼窝里只落一点很淡的阴影"),
    ("眼窝里的阴影比之前更深", "眼窝里的阴影稍深一点"),
    ("眼窝没进阴影里", "眼窝里只落一点很淡的阴影"),
]

总 = 0
for 路 in (分镜, 故事):
    if not os.path.exists(路):
        continue
    t = io.open(路, encoding="utf-8").read()
    前 = len(t)
    n = 0
    for a, b in 对表:
        c = t.count(a)
        if c:
            t = t.replace(a, b)
            n += c
    if n:
        io.open(路, "w", encoding="utf-8").write(t)
    print(f"  {os.path.basename(路)}：改 {n} 处  ({前} → {len(t)} 字节)")
    总 += n

print(f"\n共 {总} 处")

# 复验：旧写法与「否定句」都不该再出现
print("\n复验：")
for 路 in (分镜, 故事):
    if not os.path.exists(路):
        continue
    t = io.open(路, encoding="utf-8").read()
    for 坏 in ("不是黑眼圈", "不是淤青", "不是伤", "青灰色眼袋", "陷进阴影里"):
        c = t.count(坏)
        if c:
            print(f"  ✗ {os.path.basename(路)} 还剩「{坏}」×{c}")
    print(f"  {os.path.basename(路)} 查完")
