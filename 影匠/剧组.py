def 命令_全部(戏名, 强跑=False, 空跑=False, 放大=False):
    """一句话 → 成片，一路跑到底。

    ★ 跟老版本最大的区别：**卡住不整条停**。
    老版本每一步 `门()` 不过就 `return 3` —— 前面九格都出好了、第十格没过门，
    整条就断在这儿，用户看到的是「跑了半天什么都没出」，而且**不知道断在哪**。
    现在每一步单独记账：卡了就跳过记下来，能做的继续做，最后打一张表说清
    哪几步成了、哪几步跳过了、为什么。

    ★ 第二处改动：**「成片」原来不在这条链子上**。链子跑到「拼图」（一张 PNG 看片表）
    就结束了 —— 所以按「全部」永远不会得到一条能发出去的片。现在它在链尾。

    ★ 第三处：老版本没有「剧本 → 分镜」这一段。没剧本就直接停。现在没剧本会明说
    「先写剧本，或者用控台的四步卡」，其余步骤照样按现有素材跑。
    """
    头(f"全部《{戏名}》" + ("　[强跑]" if 强跑 else "") + ("　[空跑]" if 空跑 else "")
       + ("　[放大]" if 放大 else ""))
    起 = time.time()
    账 = []          # (步骤, 结果, 说明)

    def 记(步, 果, 说=""):
        账.append((步, 果, 说))
        符号 = {"✓": "✓", "跳": "⏭", "✗": "✗"}.get(果, "?")
        print(f"\n{符号} [{步}] {果}　{说}")

    命令_检查(戏名)

    # ① 剧本在不在（不在只提示，不算失败 —— 没剧本也可能是在改老片）
    目录 = 戏目录(戏名)
    if os.path.exists(os.path.join(目录, F_剧本)):
        记("剧本", "✓", "有了")
    else:
        记("剧本", "跳", "目录里没有 剧本.md —— 先在控台「新建一部戏」写一份；"
                          "下面按现有素材继续")

    # ② 出九宫格图
    if not 门(戏名, ["①", "②"], 强跑, "出九宫格图"):
        记("出图", "跳", "①/② 没有 PASS（--强跑 可以硬闯）")
    elif 命令_出图(戏名, 空跑=空跑) != 0:
        记("出图", "✗", "出图这步自己报错了 —— 看上面的输出")
    else:
        记("出图", "✓", "")

    # ③ 出四宫格图
    if not 门(戏名, ["③"], 强跑, "出四宫格图"):
        记("出图四宫格", "跳", "③ 没有 PASS")
    elif 命令_出图四宫格(戏名, 空跑=空跑) != 0:
        记("出图四宫格", "✗", "看上面的输出")
    else:
        记("出图四宫格", "✓", "")

    # ④ 出片
    if not 门(戏名, ["④"], 强跑, "出片"):
        记("出片", "跳", "④ 没有 PASS")
    elif 命令_出片(戏名, 空跑=空跑) != 0:
        记("出片", "✗", "看上面的输出")
    else:
        记("出片", "✓", "")

    if 空跑:
        记("空跑", "跳", "空跑模式：拼图/成片/进度 都不跑")
        打账(账, 起)
        return 0

    # ⑤ 拼图（看片表）
    if 命令_拼图(戏名) != 0:
        记("拼图", "跳", "还没图可拼（出图那步没成）")
    else:
        记("拼图", "✓", "")

    # ⑥ ★ 成片 —— 老版本没有这一步
    if not os.listdir(目录) or not [f for f in os.listdir(目录)
                                    if f.startswith("04_") and f.endswith(".mp4")]:
        记("成片", "跳", "一段 04_*.mp4 都没有 —— 先跑「出片」")
    elif 命令_成片(戏名, 放大=放大) != 0:
        记("成片", "✗", "看上面的输出")
    else:
        记("成片", "✓", "")

    # ⑦ 进度
    if 命令_进度(戏名) != 0:
        记("进度", "跳", "写不出来")
    else:
        记("进度", "✓", "")

    打账(账, 起)
    # 只有「成片」真失败才算整条失败；跳过是正常的（他可以只跑到一半）
    硬伤 = [x for x in 账 if x[1] == "✗"]
    return 1 if 硬伤 else 0


def 打账(账, 起时间):
    """把「全部」每一步成没成打成一张表。"""
    print()
    print("═" * 64)
    print("  这次『全部』跑到哪儿了")
    print("═" * 64)
    print(f"  {'步骤':<14}{'结果':<6}说明")
    for 步, 果, 说 in 账:
        符 = {"✓": "✓ 成了", "跳": "⏭ 跳过", "✗": "✗ 失败"}.get(果, 果)
        print(f"  {步:<14}{符:<8}{说}")
    目录 = None
    for 步, 果, 说 in 账:
        if 步 == "成片" and 果 == "✓":
            目录 = True
    print()
    print(f"  合计 {len(账)} 步：成 {sum(1 for x in 账 if x[1]=='✓')}、"
          f"跳过 {sum(1 for x in 账 if x[1]=='跳')}、"
          f"失败 {sum(1 for x in 账 if x[1]=='✗')}　⏱ {时长(time.time() - 起时间)}")
    if not 目录:
        print("  ★ 没有出成片 —— 上面写着卡在哪一步。跳过的那几步不一定是坏事："
              "没剧本、没图、没段的时候，它们本来就跑不了。")
    else:
        print("  ★ 成片在 作品\\<戏名>\\<戏名>_成片.mp4")


