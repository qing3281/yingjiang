_表行 = re.compile(r"^\|(.+)\|\s*$")
_问题行 = re.compile(r"^\*\*问题\s*(\d+)\s*\*\*\s*[:：]\s*(.+?)\s*$")


def _结果(文本):
    上 = (文本 or "").upper()
    if "PASS" in 上:
        return "PASS"
    if "FAIL" in 上:
        return "FAIL"
    return None


def 解析看片记录(路径):
    """读 看片记录.md。表格行和「✓ 审核状态：PASS」块都收，按出现顺序排。

    返回 {记录们, 告警}；每条记录带 序（行号）用于取「最后一条」。
    """
    果 = {"记录们": [], "告警": []}
    if not os.path.exists(路径):
        果["告警"].append({"行": 0, "原文": "", "说明": f"文件不存在：{路径}"})
        return 果

    待定 = None
    最近标题 = ""
    for 号, 原 in enumerate(读行(路径), 1):
        行 = 原.strip()
        if not 行:
            continue
        if 行.startswith("#"):
            最近标题 = 行.lstrip("#").strip()
            continue

        m = _表行.match(行)
        if m:
            格 = [c.strip() for c in m.group(1).split("|")]
            if len(格) >= 5:
                结果 = _结果(格[2])
                if 结果:
                    果["记录们"].append({
                        "序": 号, "轮次": 格[0], "阶段": 格[1], "结果": 结果,
                        "定位": 格[3], "摘要": 格[4], "类型": "表", "标题": 最近标题,
                        "问题们": [], "原文": 行,
                    })
                    continue

        if "审核状态" in 行:
            结果 = _结果(行)
            if 结果:
                待定 = {"序": 号, "轮次": "", "阶段": "", "结果": 结果, "定位": "",
                        "摘要": "", "类型": "块", "标题": 最近标题,
                        "问题们": [], "原文": 行}
                果["记录们"].append(待定)
            continue

        if 待定 is not None and not 待定["阶段"]:
            m2 = re.search(r"【(.+?)】", 行)
            if m2:
                待定["阶段"] = m2.group(1).strip()
                continue
        if 待定 is not None:
            m3 = _问题行.match(行)
            if m3:
                待定["问题们"].append(m3.group(2))
    return 果


