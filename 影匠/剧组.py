def 命中(规格, 文本):
    if not 文本:
        return False
    for 词 in 规格.get("排", []):
        if 词 in 文本:
            return False
    for 组 in 规格["组"]:
        if not any(词 in 文本 for 词 in 组):
            return False
    return True


def 审片状态(记录们, 键):
    """看片记录是追加写的 —— 取**最后一条**能对上的记录当下状态。

    返回 (结果, 记录)：结果是 PASS / FAIL / "无"（没这个阶段的记录）。
    """
    规格 = _规格[键]
    命中们 = [r for r in 记录们 if 命中(规格, r.get("阶段") or r.get("标题", ""))]
    if not 命中们:
        return "无", None
    r = max(命中们, key=lambda x: x["序"])
    return r["结果"], r


