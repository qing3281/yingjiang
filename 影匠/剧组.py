def 找ffmpeg():
    """项目自带的 _bin\\ffmpeg.exe 优先，没有再退回 PATH。

    ★ _bin 里**只有 ffmpeg.exe，没有 ffprobe.exe**。别拿 ffmpeg 改名当 ffprobe 用
    （`_烧字幕.py` 踩过：异常被吞掉，探时长永远回 0，于是「时长差 > 0.5 秒就报错」
    那条检查变成了永远说 OK 的检查）。这里一律用 `ffmpeg -i` 的 stderr 读时长。
    """
    本 = os.path.join(这里, "_bin", "ffmpeg.exe")
    if os.path.exists(本):
        return 本
    return shutil.which("ffmpeg") or "ffmpeg"


def 探时长(ff, 路):
    """用 ffmpeg -i 的 stderr 读时长（没有 ffprobe）。读不到就抛，不许回 0 蒙过去。"""
    环 = {**os.environ, "PYTHONIOENCODING": "utf-8"}
    r = subprocess.run([ff, "-hide_banner", "-i", 路], capture_output=True, env=环)
    文 = (r.stderr or b"").decode(U8, "replace")
    m = re.search(r"Duration:\s*(\d+):(\d+):(\d+(?:\.\d+)?)", 文)
    if not m:
        raise RuntimeError("读不出时长：%s" % 路)
    return int(m.group(1)) * 3600 + int(m.group(2)) * 60 + float(m.group(3))


def 数帧(ff, 路, 环=None):
    """数一条片里真实有多少帧。

    为什么要数帧而不是看时长：**时长会说谎**。实测《修鞋》那 10 段直接 concat 之后，
    865 帧的片子里报出 `Duration 54.79` 秒（平均 15.8fps）—— 因为各段 PTS 各自从 0 开始，
    时间戳叠在一起了。只看 Duration 会以为「成片 55 秒，正好」，其实画面全堆在前 36 秒。
    """
    环 = 环 or {**os.environ, "PYTHONIOENCODING": "utf-8"}
    r = subprocess.run([ff, "-hide_banner", "-i", 路, "-map", "0:v:0", "-f", "null", "-"],
                       capture_output=True, env=环)
    文 = (r.stderr or b"").decode(U8, "replace")
    m = re.findall(r"frame=\s*(\d+)", 文)
    return int(m[-1]) if m else 0


