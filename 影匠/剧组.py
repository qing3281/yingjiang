_编码已报 = set()          # 非 UTF-8 文件只提醒一次


def 读行(路径):
    """读成行列表。真 UTF-8 优先；不是 UTF-8（比如记事本存成了 ANSI）就退回本地编码，并当场报警。

    退回时行号**依然有效**（按本地编码切行），所以告警里的行号还能用。
    同一个文件只报一次（一条命令里同一张纸可能被解析好几遍）。
    """
    with open(路径, "rb") as f:
        原始 = f.read()
    try:
        return 原始.decode(U8).splitlines()
    except UnicodeDecodeError as 错:
        备 = locale.getpreferredencoding(False) or "gbk"
        try:
            行们 = 原始.decode(备, "replace").splitlines()
        except LookupError:
            备, 行们 = "utf-8+replace", 原始.decode(U8, "replace").splitlines()
        if 路径 not in _编码已报:
            _编码已报.add(路径)
            print(f"⚠ {os.path.basename(路径)} 不是 UTF-8（第 {错.start} 字节起解不开）—— "
                  f"按 {备} 硬读，行号照旧。建议存成 UTF-8。")
        return 行们


