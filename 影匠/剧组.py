def 拆名字(s):
    出 = []
    for x in re.split(r"[、，,；;/|+\s]+", s or ""):
        x = re.sub(r"[（(].*?[)）]", "", x).strip()
        if x and x not in 出:
            出.append(x)
    return 出


def 挑角色(文本, 名单):
    """这格谁出场：名字直接出现在文本里的算。

    三档：
      ① 文本里认得出名字        → 就用认出来的
      ② ★ 文本明写「画面里没有一个人」（空镜头）→ **一个人都不加**
      ③ 一个都没认出来          → 只有 1 个角色就用它；多个就把全体带上并报一句

    ★ 2026-10-15 晚加的第 ② 档。病根：格11（空电影院闪回）、格12（空水族馆+摩天轮）、
      格29/31/32（空宿舍）这些**空镜头**，提示词里自然不会出现角色名，
      于是走到第 ③ 档、被塞进全体角色 —— 实测 32 格里出现了「空电影院里站着两个人」
      「同一个画面里两个夏弥」。空镜头得有一个**明确**的表达方式。

    返回 (角色们, 备注)。
    """
    文 = 文本 or ""
    # ★★ 2026-10-16 凌晨再修：**只拿【位置】那一段来认名字。**
    #   病根（用户亲眼看见的「格21 里凭空多出一个夏弥」）：
    #   拼好的提示词是「画面的布局是：<位置>。这一格的视角是：<机位>。…<画面>…<动作>…」。
    #   格21 的【位置】写的是「画面右边远处只有很小一点模糊的白瓷砖柱子；画面里只有他一个
    #   清晰的人」—— **根本没点夏弥的名**；可【画面】里有一句「还有夏弥眼睛里的金色」，
    #   于是「夏弥」被认了出来，整段【龙化档】（脖子锁骨肩膀覆着一片一片黑鳞…）跟着拼进去，
    #   模型只好在画面右边凭空造一个清清楚楚的夏弥出来。
    #   ★ 新判据：**谁出场，由【位置】说了算** —— 位置是这一格构图的权威。
    #     画面里提到名字不等于这个人在场（可能只是「她眼睛里的光」照到他背上）。
    #   从拼好的提示词里把【位置】那一段切出来；切不出来（老格式）就退回整段。
    if "画面的布局是：" in 文:
        段 = 文.split("画面的布局是：", 1)[1]
        for 停 in ("这一格的视角是", "这一格的视角", "取景框里"):
            if 停 in 段:
                段 = 段.split(停, 1)[0]
                break
        文 = 段
    # ★ 2026-10-16 凌晨重排：**先认名字，再判空镜头**。
    #   病根：原来空镜头那一档排在最前面，于是「画面里只有楚子航一个人」这种
    #   明明点了名的句子会被前面的空话命中、判成空镜头。名字的优先级最高。
    有 = [n for n in 名单 if n and n in 文]
    if 有:
        return 有, ""
    # ★ 空镜头统一成一条**前缀规矩**：「画面里只有……」后面没跟任何角色名 → 一个人都不加。
    #   这样一格空镜头（一颗龙眼、一条龙、一扇窗、一盏风铃、一只手、一条路）不必
    #   每样都往下面那张表里加一个词。
    if "画面里只有" in 文:
        return [], ""
    for 空话 in ("画面里没有一个人", "画面里没有人", "一个人都没有", "没有一个人",
                 "玻璃前面没有人", "轿厢里没有人", "房间里没有别人", "没有人",
                 "没有别人", "没有其他人物"):
        if 空话 in 文:
            return [], ""
    if len(名单) == 1:
        return list(名单), ""
    if not 名单:
        return [], ""
    return list(名单), "提示词里没认出角色名，本格按全体角色处理（想让某格只带某几个人，就在提示词里写名字）"


def 角色种子(文本, 名单):
    """这格的种子（导演.开镜 用的就是它：锁第一个出场角色的种子）。"""
    for n in 挑角色(文本, 名单)[0]:
        r = 角色库.取(n)
        if r:
            return r["种子"]
    return None


def 环境串(视觉规范: dict) -> str:
    """把 02-九宫格.md 的【视觉规范】拼成一段能进提示词的环境描写。

    ★ 2026-10-15 晚新加。病根：`取风格()` 只取「风格」一条，
    `色彩光影` / `材质` / `机位规矩` 这三条**解析出来就扔了**，
    所以「全片在阴暗的地铁隧道里」这句话从来没到过模型眼前。
    ★ 只取【色彩光影】和【材质】两条。
      **不取【机位规矩】** —— 那条写的是「全片没有一个俯拍」，是**否定句**，
      进提示词只会把「俯拍」两个字叫出来（病 #5）。机位规矩是给我自己看的，不是给模型的。
    """
    段 = []
    for 键 in ("色彩光影", "材质"):
        值 = (视觉规范 or {}).get(键) or ""
        if 值.strip():
            段.append(值.strip())
    return "；".join(段)


def 取风格(视觉规范):
    """视觉规范里的「风格」→ 交给 导演.开镜。认不出来就退回戏的默认。"""
