def 宽(s):
    """按显示宽度算（中文算 2 格），这样表格对得齐。"""
    return sum(2 if unicodedata.east_asian_width(c) in "WF" else 1 for c in s)


def 排(s, n):
    return s + " " * max(0, n - 宽(s))


def 大小(字节):
    if 字节 < 1024:
        return f"{字节} B"
    if 字节 < 1024 ** 2:
        return f"{字节 / 1024:.1f} KB"
    return f"{字节 / 1024 ** 2:.1f} MB"


