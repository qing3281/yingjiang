def 分镜宽高():
    """九宫格那张图出多大。★ 2026-10-15 深夜加。

    病根：`导演.开镜()` 的宽高默认是 **1024×1024（正方形）**，出图那两处都没传，
    于是 32 张分镜全是正方形。可是**出片那一路（MiniMax-H3 / Wan）全都是 832×480（16:9）**，
    定妆卡又是 1152×1536（3:4）。**一张 1:1 的图喂进 16:9，要么裁掉上下（头顶和脚就没了）、
    要么压扁。** 所以分镜必须跟片子同画幅。

    1344×768 和 832×480 都是 7:4 的 16:9 家族，先出大图再缩，细节多。
    想改就在 `设置.json` 里写 `分镜宽` / `分镜高`。
    """
    d = 导演.读设置()
    try:
        w = int(d.get("分镜宽") or 1344)
        h = int(d.get("分镜高") or 768)
    except (TypeError, ValueError):
        w, h = 1344, 768
    return w, h


