# -*- coding: utf-8 -*-
"""给《磨刀》六个说话人挑音色 —— 按**文件名关键词**找，再逐个真解码验。

为什么按文件名找：`音色库.json` 的元数据太稀（1415 条里 967 条性别是空、1218 条年龄是空），
光靠字段筛不出「青年男」（0 条）。但文件名的信息量比字段大得多 ——
`男-奸诈狡猾 老谋深算.wav` 这种名字本身就是选角说明。

验什么：能解出音频、采样率、时长、RMS、峰值、有没有削波。**只看文件存在是不够的**
（这一路上「文件在 ≠ 文件对」已经栽过两次）。
"""
import json
import os
import sys

import numpy as np
import soundfile as sf

根 = r"D:\DSHworkspace\影匠\音色"
库 = json.load(open(os.path.join(根, "音色库.json"), encoding="utf-8"))["音频"]
相对集 = {x["相对"] for x in 库}

# 选角意图 → 文件名关键词（按优先级，先命中的赢）
想要 = {
    "沈砚":   ["冷感克制的清冽的闷油瓶男声", "男-低音、正派、冷静",
               "男-常规-清冷无情-3-1", "男-中音,中等,清冷", "男-中音、清冷、木楞"],
    "赵崇武": ["男-低音，威严，浓厚", "中年男声（45岁±）",
               "男-沧桑 沙哑 岁月沉淀", "男-浓重醇厚 低沉中老年", "质感叔音"],
    "阿七":   ["男-奸诈狡猾 老谋深算", "男-中音、阴阳怪气",
               "男-清冷刻薄、傲慢自大", "男-中音、心思深沉"],
    "阿满":   ["女-直爽、直来直往、女侠", "女-开朗、靠谱、丫鬟",
               "女-单纯天真、村妇", "女-大方机灵、将军"],
    "周泰":   ["流氓地痞-中音、嚣张、流氓", "男-低音、凶狠",
               "男-傲慢刻薄、凶狠", "男-傲慢、狂妄"],
    "少年沈砚": ["男-十二到十四岁的男孩", "男-8-10岁的小男孩", "男-6-8岁的小男孩"],
    "旁白":   ["磁性悬疑嗓，带你穿越武侠与战场",
               "磁性御姐音，影视解说气场全开", "文学旁白解说（男声）"],
}


def 找(词表):
    for w in 词表:
        命 = [x for x in 库 if w in x["名字"] or w in x["相对"]]
        if 命:
            # 同名的取最长的（样本更足）
            return sorted(命, key=lambda x: -x["秒"])[0], w
    return None, ""


def 验(绝对路):
    try:
        声, 率 = sf.read(绝对路, dtype="float32", always_2d=True)
    except Exception as e:  # noqa: BLE001
        return None, f"{type(e).__name__}: {e}"
    x = 声.mean(axis=1)
    峰 = float(np.max(np.abs(x)))
    return {
        "秒": len(x) / 率, "率": 率, "道": 声.shape[1],
        "峰": 峰, "有效值": float(np.sqrt((x ** 2).mean())),
        "削波": float((np.abs(x) > 0.999).mean() * 100),
    }, ""


print(f"{'角色':<10} {'命中关键词':<22} {'采样':>5} {'时长':>6} {'RMS':>7} {'峰值':>6} 状态")
print("─" * 96)
结果 = {}
for 角色, 词表 in 想要.items():
    x, 词 = 找(词表)
    if not x:
        print(f"{角色:<10} ✗ 一个关键词都没命中：{词表}")
        continue
    绝 = os.path.join(根, "原声", x["相对"].replace("/", os.sep))
    在库 = x["相对"] in 相对集
    if not os.path.exists(绝):
        print(f"{角色:<10} ✗ 文件不在：{绝}")
        continue
    量, 错 = 验(绝)
    if 错:
        print(f"{角色:<10} ✗ 解不开：{错}")
        continue
    好 = 量["秒"] >= 3 and 量["峰"] > 0.05 and 量["削波"] < 1
    print(f"{角色:<10} {词:<22} {量['率']:>5} {量['秒']:>5.2f}s "
          f"{量['有效值']:>7.4f} {量['峰']:>6.3f} "
          f"{'✓' if 好 else '⚠ 样本偏短/偏轻'}  库内={在库}")
    print(f"           {x['相对']}")
    结果[角色] = x["相对"]

print("\n=== 给 音色\\角色映射.json 用的片段 ===")
print(json.dumps(结果, ensure_ascii=False, indent=2))
