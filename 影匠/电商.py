def 登记(名, 路, 文件类型, 提示词, 面板id, 标题=""):
    """记一条归档。结构照飞彩原文：

    {id,taskId:`ecom-${Date.now()}`,fileUrl,fileType,prompt,platform:"thirdparty",
     createdAt,dateFolder,source:"ecommerce",module,title?}
    """
    d = 读归档()
    条 = {
        "id": f"{面板id}-{int(datetime.now().timestamp()*1000)}",
        "taskId": f"ecom-{int(datetime.now().timestamp()*1000)}",
        "fileUrl": os.path.abspath(路),
        "fileType": 文件类型,                       # image | video
        "prompt": (提示词 or "(电商生成)")[:2000],
        "platform": "thirdparty",
        "createdAt": _现在(),
        "dateFolder": _日期夹(),
        "source": "ecommerce",                       # 飞彩查询过滤 source==="ecommerce"
        "module": 面板id,
        "product": 名,
    }
    if 标题:
        条["title"] = 标题
    d["assets"] = [条] + d["assets"]
    if len(d["assets"]) > 最多归档:
        d["assets"] = d["assets"][:最多归档]
    # 同时并进商品工程
    工 = _读json(商品文件(名))
    if 工 is not None:
        工.setdefault("产物", []).append(条)
        _写json(商品文件(名), 工)
    路径 = os.path.join(面板目录(名, 面板id), "归档.json") if 面板id in 面板表 else None
    if 路径:
        p = _读json(路径, {"assets": []}) or {"assets": []}
        p["assets"] = [条] + p.get("assets", [])
        _写json(路径, p)
    _写json(归档文件, d)
    return 条


def 查归档(面板id=None, 名=None, 关键词=""):
    """对应飞彩「历史图库 / 视频库」的过滤：source==="ecommerce" && module && fileType。"""
    出 = []
    for a in 读归档()["assets"]:
        if a.get("source") != "ecommerce":
            continue
        if 面板id and a.get("module") != 面板id:
            continue
        if 名 and a.get("product") != 名:
            continue
        if 关键词:
            k = 关键词.lower()
            if k not in str(a.get("prompt", "")).lower() and k not in str(a.get("title", "")).lower():
                continue
        出.append(a)
    return 出


