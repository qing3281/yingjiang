def _拆参考图(参考图):
    if not 参考图:
        return []
    if isinstance(参考图, (list, tuple)):
        们 = list(参考图)
    else:
        们 = [x for x in re.split(r"[,，;；]+", str(参考图)) if x.strip()]
    出 = []
    for p in 们:
        p = str(p).strip().strip('"')
        if not p:
            continue
        if not os.path.isabs(p):
            p = os.path.join(_根, p)
        if os.path.isfile(p):
            出.append(os.path.abspath(p))
        else:
            警(f"参考图找不到，跳过：{p}")
    return 出


def _比例像素(比例):
    return 比例像素.get(比例 or "1:1", (1024, 1024))


def 出一张(提示词, 存到, 参考图=None, 比例="1:1", 风=None, 宽=None, 高=None):
    """出一条图。接 引擎.py 的 文生图(提示词, ..., 参考图=[...], 存到=...)。

    引擎.py 原文：给了参考图就自动改走 qwen_edit（image1/image2/image3 三个槽，最多 3 张）。
    """
    if _引擎 is None:
        raise RuntimeError(f"引擎.py 没载入：{_引擎错}")
    风 = 风 or {"正向": "", "负向": ""}
    全 = 提示词
    if 风["正向"]:
        全 = f"{风['正向']}，{提示词}"
    w, h = _比例像素(比例) if not (宽 and 高) else (宽, 高)
    参 = dict(提示词=全, 负面=风.get("负向") or "", 宽=w, 高=h,
              报=lambda s: None, 存到=存到)
    参图 = list(参考图 or [])[:3]        # 引擎.py 的 qwen_edit 只有 3 个槽
    if 参图:
        参["参考图"] = 参图
    if 风.get("cfg"):
        # 风格库给的 cfg 通过 配置 透传（引擎.py 支持 配置:dict）
        参["配置"] = {"cfg": 风["cfg"]}
    果 = _引擎.文生图(**参)
    路 = (果 or {}).get("路") or 存到
    return os.path.abspath(路), 果


def 出一段片(提示词, 存到, 图路=None, 风=None, 比例="9:16"):
    """出一段片。接 引擎.py 的 图生视频(图路, 提示词, ...)。

    引擎.py 没有纯文生视频 —— 没图时先出一张首帧再喂进去。
    """
    if _引擎 is None:
        raise RuntimeError(f"引擎.py 没载入：{_引擎错}")
    风 = 风 or {"正向": "", "负向": ""}
    全 = f"{风['正向']}，{提示词}" if 风["正向"] else 提示词
    if not 图路 or not os.path.isfile(图路):
        首 = os.path.splitext(存到)[0] + "_首帧.png"
        w, h = _比例像素(比例)
        图路, _ = 出一张(全, 首, 比例=比例, 风=风, 宽=w, 高=h)
    果 = _引擎.图生视频(图路, 全, 负面=风.get("负向") or "",
                      报=lambda s: None, 存到=存到)
    路 = (果 or {}).get("路") or 存到
    return os.path.abspath(路), 图路, 果


