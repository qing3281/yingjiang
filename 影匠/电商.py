def _选参(参, 面板id, 题):
    """把 --类型 / --平台 / --语言 / 各单选项填成飞彩的多选/单选值。"""
    p = 面板表[面板id]
    for 名, 默认 in (p.get("单选") or {}).items():
        v = 参.get(名)
        if v in (None, ""):
            参[名] = 默认[0]
        elif v not in 默认:
            警(f"{题}：{名} 「{v}」不在飞彩的选项里 {默认}，照用")
    for 名, 默认 in (p.get("多选") or {}).items():
        v = 参.get(名)
        if isinstance(v, str):
            v = [x for x in re.split(r"[,，、\s]+", v) if x.strip()]
        if not v:
            v = list((p.get("默认多选") or {}).get(名) or [默认[0]])
            if 参.get("_用户给了类型") is None and 名 in ("图片类型", "视频类型", "详情页模块", "海报类型"):
                参["_用了默认"] = True
        坏 = [x for x in v if x not in 默认]
        if 坏:
            警(f"{题}：{名} 里 {坏} 不在飞彩的选项里 {默认}，照用")
        参[名] = v
    return 参


def 命令_出图(商品名, 面板id, 参=None, 空跑=False, json出=False, 重做=False,
              风格键=普通风格, 拼长图=False):
    参 = dict(参 or {})
    p = 面板表[面板id]
    头(f"{p['名']}《{商品名}》" + ("　[空跑]" if 空跑 else ""))
    工 = _读json(商品文件(商品名))
    if not 工:
        return _没这商品(商品名, json出)

    _选参(参, 面板id, p["名"])
    参考图 = _拆参考图(参.get("参考图"))
    if p.get("必参考图") and not 参考图:
        # 飞彩这几个面板上传是必填
        if not 空跑:
            错(f"{p['名']}必须传参考图。{ '、'.join(p['要']) }")
            错(f"例如：python 电商.py {面板id} {商品名} --参考图 商品图.jpg")
            return _交(json出, {"ok": False, "错误": "缺参考图", "面板": p["名"],
                                "要": p["要"]}, 2)
    if p.get("参考图上限") and len(参考图) > p["参考图上限"]:
        警(f"飞彩这个面板最多 {p['参考图上限']} 张参考图，收到 {len(参考图)} 张，只用前 {p['参考图上限']} 张")
        参考图 = 参考图[:p["参考图上限"]]
    if len(参考图) > 3:
        警(f"引擎.py 的 qwen_edit 只有 3 个参考图槽（image1/image2/image3），只用前 3 张")
        参考图 = 参考图[:3]

    比例 = 参.get("生成比例") or 参.get("目标比例") or 参.get("尺寸比例") or p.get("默认比例", "1:1")
