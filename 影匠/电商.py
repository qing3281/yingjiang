def _写json(路径, 数据):
    os.makedirs(os.path.dirname(路径), exist_ok=True)
    with open(路径, "w", encoding="utf-8") as f:
        json.dump(数据, f, ensure_ascii=False, indent=1)
    return 路径


def _读json(路径, 兜底=None):
    if not os.path.isfile(路径):
        return 兜底
    try:
        with open(路径, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return 兜底


def _写文(路径, 文字):
    os.makedirs(os.path.dirname(路径), exist_ok=True)
    with open(路径, "w", encoding="utf-8") as f:
        f.write(文字)
    return 路径


