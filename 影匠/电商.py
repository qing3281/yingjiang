def 命令_抹除(商品名, 参考图="", 强度="中度", 素材类型="图片",
              空跑=False, json出=False, 重做=False, 风格键=""):
    头(f"AI 抹除《{商品名}》　强度 {强度}　素材 {素材类型}" + ("　[空跑]" if 空跑 else ""))
    报("飞彩原文副标题：" + 面板表["aiclean"]["副标题"])
    报("飞彩接口：POST /api/media-deai body={mediaUrl,level,kind:\"image\"|\"video\",projectId} → {outputUrl}")
    报("              level ∈ light / medium / heavy（飞彩 eV 原文：轻度/中度/重度）")
    强度英文 = {"轻度": "light", "中度": "medium", "重度": "heavy"}.get(强度, 强度)
    if 强度英文 not in ("light", "medium", "heavy"):
        警(f"抹除强度「{强度}」不在飞彩三档里，按 中度(medium) 来")
        强度英文, 强度 = "medium", "中度"
    报(f"→ level={强度英文}　kind={'video' if 素材类型=='视频' else 'image'}")

    工 = _读json(商品文件(商品名))
    if not 工:
        return _没这商品(商品名, json出)
    参考 = _拆参考图(参考图)
    if not 参考 and not 空跑:
        错("抹除要传素材。例如：python 电商.py 抹除 " + 商品名 + " --参考图 商品图.jpg --强度 medium")
        return _交(json出, {"ok": False, "错误": "缺素材"}, 2)

    提 = _兜底提示词("aiclean", {"抹除强度": 强度})
    if 空跑:
        报(f"[空跑] 要处理 {len(参考)} 个素材 → {面板目录(商品名,'aiclean')}")
        报(f"[空跑] 提示词：{提}")
        return _交(json出, {"ok": True, "空跑": True, "level": 强度英文, "素材": len(参考)}, 0)

    _确保目录(商品名, "aiclean")
    风 = 编译风格(风格键)
    做成 = 失败 = 0
    for i, src in enumerate(参考, 1):
        目标 = os.path.join(面板目录(商品名, "aiclean"), f"aiclean-{i:02d}.png")
        if os.path.isfile(目标) and not 重做:
            报(f"跳过（已有）：{os.path.basename(目标)}")
            continue
        try:
            # 影匠没有飞彩的 /api/media-deai，改用图生图重绘来压 AI 痕迹（等价思路）
            路, _ = 出一张(提, 目标, 参考图=[src], 比例="1:1", 风=风)
            做成 += 1
            登记(商品名, 路, "image", 提, "aiclean", f"{强度}抹除")
        except Exception as e:
            失败 += 1
            警(f"抹除异常（{os.path.basename(src)}）：{type(e).__name__}: {e}")
    报(f"处理 {做成} 个，失败 {失败} 个 → {面板目录(商品名,'aiclean')}")
    工.setdefault("panelRuns", {})["aiclean"] = {"at": _现在(), "成": 做成, "败": 失败,
                                                 "level": 强度英文}
    _写json(商品文件(商品名), 工)
    return _交(json出, {"ok": 做成 > 0, "做成": 做成, "失败": 失败, "level": 强度英文},
               0 if 做成 > 0 else 4)


