def _兜底提示词(面板id, 参, i=0):
    """没给 --提示词 时，按飞彩的 userInput 直接拼一句能用的中文（不臆造产品外形）。"""
    产 = 参.get("产品名称") or 参.get("主题/标题") or "商品"
    规 = "，商品居中，干净背景，均匀柔光，商业质感，无任何文字水印"
    if 面板id == "zhutu":
        t = (参.get("图片类型") or ["引流封面"])[0]
        return f"电商主图·{t}：{产}，突出{参.get('商品卖点','') or '产品本身'}，{参.get('输出平台','淘宝')}平台风格{规}"
    if 面板id == "detail":
        m = (参.get("详情页模块") or ["头图"])[0]
        return f"电商详情页·{m}模块：{产}，清晰信息层级与规整版式，{参.get('输出平台','淘宝')}平台风格{规}"
    if 面板id == "poster":
        t = (参.get("海报类型") or ["节日促销"])[0]
        return f"电商促销海报·{t}：主视觉围绕「{产}」，{参.get('海报文案','') or '促销信息清晰'}，价格用人民币¥，构图有冲击力"
    if 面板id == "whitebg":
        t = "、".join(参.get("处理类型") or ["纯白底"])
        return f"把商品精准抠出并置于{参.get('输出尺寸','800×800')}的{t}背景中央，去除原图所有杂物，保持商品比例与标签文字清晰，光线均匀，符合电商主图规范"
    if 面板id == "clone":
        return f"沿用参考设计的构图、配色与光影氛围，把画面主体替换成第二个参考图里的产品，保持真实外形、比例、材质与 Logo 不变形，{参.get('替换说明','') or '做到神似参考又是全新原创'}"
    if 面板id == "ratio":
        return f"把图片调整为{参.get('目标比例','1:1')}画幅，用「{'、'.join(参.get('填充方式') or ['智能扩图AI外绘'])}」补全画面，商品主体不变形不裁切，扩展区域与原图无缝衔接"
    if 面板id == "translate":
        return f"识别图中所有文字并翻译为{参.get('目标语言','英语')}，在原位置重排译文，保持原版式、字体风格与配色不变，商品与背景维持原样，画面整洁无溢出"
    if 面板id == "aiclean":
        return (f"对素材做{参.get('抹除强度','中度')}去 AI 痕迹处理：保留商品主体外形、材质、Logo 与文字，"
                f"消除过度平滑的塑料感与 AI 特有的高频纹理，补回自然的胶片颗粒与真实光影细节，"
                f"画面看起来像真实拍摄的商品照片")
    if 面板id == "video":
        return 生成用提示词(面板id, 参)
    return f"{产}{规}"


