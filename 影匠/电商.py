def 编译风格(风格键=""):
    """返回 {正向,负向,cfg,风格}。照 风格库.py 编译() 的返回结构。"""
    空 = {"正向": "", "负向": "", "cfg": None, "风格": ""}
    if _风格库 is None:
        return 空
    try:
        键 = 风格键
        if not 键:
            ks = _风格库.全部() or []
            # 电商默认用第一个看得过去的；找不到就空手
            键 = ks[0] if ks else ""
        if not 键:
            return 空
        d = _风格库.编译(键) or {}
        if d.get("错"):
            警(f"风格库说：{d['错']}（按不带风格前缀继续）")
        return {"正向": d.get("正向") or "", "负向": d.get("负向") or "",
                "cfg": d.get("cfg"), "风格": d.get("风格") or 键}
    except Exception as e:
        警(f"风格库编译失败（{type(e).__name__}: {e}）")
        return 空


