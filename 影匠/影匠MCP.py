"""
影匠 MCP 服务器 —— 把「导演 → 演员 → 放映员」这条流水线开放给 AI
================================================================

一个零依赖（纯标准库）的 MCP（Model Context Protocol）服务器，
用 stdio + JSON-RPC 2.0 换行分帧（NDJSON）说话。
能被 DeepSeek Harness / Claude Desktop / Claude Code 等任何 MCP 宿主直接挂载。

它做的事：把 `导演.py` 那一层的能力，翻译成 AI 能调的 11 个工具
    立戏 → 定角 → 开镜 → 让镜动 → 查进度 / 审片 / 列风格 / 列戏
    另加 剧本（读剧本拿下一步）、看镜（看某个镜头出图了没）、连镜（同风格再来一镜）

用法（宿主配置里写）：
    python D:\\DSHworkspace\\影匠\\影匠MCP.py

自测：
    echo '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{}}' | python 影匠MCP.py

------------------------------------------------------------
设计要点（都是从「AI 怎么用工具」倒推出来的，不是从「代码怎么写」）
------------------------------------------------------------
1. **stdout 是协议通道，必须绝对纯净。**
   影匠的模块（导演.py / 引擎.py / 剧组.py）全是 `print` 报进度的。
   所以本服务器在**每一次**加载模块、调用模块时，都用 `安静()` 把 stdout 拦下来，
   进度改走 `报=` 回调 → 装进返回值的 `日志` 数组。stderr 留给人类排障。

2. **统一错误信封，不抛异常给宿主。**
   任何失败都返回 `{ok:false, error:{码, 说明, 建议, 可重试, 下一步}}`。
   `可重试=false` 是给 AI 的刹车：比如「出图中途断了」—— 图可能已经出了，
   重发可能白烧一遍算力，必须先 `查进度` 查证。

3. **每个返回都带 `下一步`。**
   AI 不需要记住流水线顺序，照着上一步返回的 `下一步` 走就行。
   错误返回里**也**带 —— 让它知道怎么解开，而不是盲目重试。

4. **无状态化处理全局的「当前戏」。**
   `导演.py` 用模块级 `_当前戏` 存当前在拍哪部。MCP 是并发宿主，
   不能让工具依赖「上一步 AI 调了什么」。所以每个工具都**显式**收 `戏名`，
   内部临时切过去、干完再切回来（`_在戏里()`）。

5. **用中文工具名。**
   MCP 允许任意字符串做工具名，AI 读中文名 + 中文 description 比读
   `create_shot` 猜语义要准。参数名也中文，description 里写清约束。
"""

