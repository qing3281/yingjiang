# 四、戏的解析 + 「当前戏」安全切换
# ============================================================

class 在戏里:
    """
    临时代替 `导演._当前戏`，干完恢复原样。

    `导演.py` 靠模块级 `_当前戏` 记「现在在拍哪部」。MCP 宿主会并发调工具，
    如果依赖「上一步 AI 调了什么」，串台是迟早的事。所以：
    每个工具都显式收 `戏名`，进门前切过去、出门前切回来。

    顺带做一件事：如果这部戏的目录不存在，**不自动建**，而是报错 ——
    因为「戏名打错一个字」和「想开新戏」在 AI 那里长得一样，
    自动建目录会把错字变成一部空戏，非常难查。要开新戏请用 `立戏`。
    """

    def __init__(self, 戏名, 要求存在=True):
        self.要 = str(戏名 or "").strip()
        self.要求存在 = 要求存在
        self.旧 = None
        self.目录 = None

    def __enter__(self):
        表, 错 = 装载()
        if 错:
            raise _装载失败(错)
        if not self.要:
            raise _参数不行("戏名是必填的。先 `列戏` 看看有哪些戏，或者用 `立戏` 开一部新的。")

        导 = 表["导演"]
        self.旧 = dict(导._当前戏)
        self.目录 = os.path.join(作品目录, 导._安全名(self.要))

        if self.要求存在 and not os.path.isdir(self.目录):
            有们 = 列戏目录()
            raise _没有这部戏(self.要, 有们)

        # 切过去 —— 让 导演.开镜 / 导演.让镜动 能找到目录、能用这部戏的默认风格
        导._当前戏["名"] = self.要
        导._当前戏["风格"] = self.旧.get("风格") or "cinematic-real"
        return self

    def __exit__(self, *a):
        if self.旧 is not None:
            try:
                表, _ = 装载()
                表["导演"]._当前戏.update(self.旧)
            except Exception:  # noqa: BLE001
                pass
        return False


class _装载失败(Exception):
    def __init__(self, 信封):
        super().__init__(信封["error"]["说明"])
        self.信封 = 信封


class _参数不行(Exception):
    pass


class _没有这部戏(Exception):
    def __init__(self, 戏名, 有们):
        super().__init__(戏名)
        self.戏名 = 戏名
        self.有们 = 有们

    def 信封(self):
        return 败(
            "没有这部戏",
            f"「{self.戏名}」在 作品/ 下没有目录。",
            建议=(
                ("现在有的是：" + "、".join(self.有们)) if self.有们
                else "作品/ 下还没有任何戏。"
            ) + "　要开新戏请用 `立戏`；只是去打错字，先 `列戏` 核对戏名。",
            可重试=False,
            下一步="列戏" if self.有们 else "立戏",
        )


def 列戏目录():
    """作品/ 下的所有戏名（只读，绝不建目录）。"""
    if not os.path.isdir(作品目录):
        return []
    return sorted(
        d for d in os.listdir(作品目录)
        if os.path.isdir(os.path.join(作品目录, d)) and not d.startswith(("_", "."))
    )


def 包起来(函):
    """
    把一个工具函数的异常统一翻译成错误信封。

    三层兜底：
      _装载失败 / _参数不行 / _没有这部戏  → 各自的结构化信封
      RuntimeError / OSError                → 「跑挂了」，可重试=False（先查证）
      Exception                            → 「内部出错」，带类型名，绝不崩服务器
    """
    def 壳(参):
        try:
            return 函(参)
        except _装载失败 as e:
            return e.信封
        except _参数不行 as e:
            return 败("参数不对", str(e), 建议="照 tools/list 里的 schema 传；戏名/风格键先查再传。",
                      可重试=True, 下一步="")
        except _没有这部戏 as e:
            return e.信封()
        except (RuntimeError, OSError) as e:
            return 败(
                "跑挂了",
                f"{type(e).__name__}: {e}",
                建议=(
                    "这是影匠/ComfyUI 侧的失败。若是出图或出片中途断的，"
                    "产物可能已部分落盘 —— 先 `查进度` 或 `看镜` 查证，别直接重发。"
                ),
                可重试=False,
                下一步="查进度",
            )
        except Exception as e:  # noqa: BLE001 —— 兜底，绝不让服务器死掉
            return 败(
                "内部出错",
                f"{type(e).__name__}: {e}",
                建议="这是本服务器自己的 bug，不是影匠的问题。把 说明 连同调用参数报给用户。",
                可重试=False,
                回溯=traceback.format_exc()[-1200:],
            )
    return 壳


# ============================================================
# 五、工具参数校验（够用就好的小校验器）
# ============================================================

def 要串(参, 键, 必填=True, 缺省="", 最长=None):
    值 = 参.get(键, 缺省)
    if 值 is None:
        值 = 缺省
    值 = str(值).strip()
    if 必填 and not 值:
        raise _参数不行(f"`{键}` 不能空。")
    if 最长 and len(值) > 最长:
        raise _参数不行(f"`{键}` 太长（{len(值)} 字，上限 {最长}）。")
    return 值


def 要整(参, 键, 缺省=None, 最小=None, 最大=None):
    值 = 参.get(键, 缺省)
    if 值 is None or 值 == "":
        if 缺省 is None:
            raise _参数不行(f"`{键}` 必填。")
        return 缺省
    try:
        值 = int(值)
    except (TypeError, ValueError):
        raise _参数不行(f"`{键}` 要整数，收到 {参.get(键)!r}。")
    if 最小 is not None and 值 < 最小:
        raise _参数不行(f"`{键}` 不能小于 {最小}（收到 {值}）。")
    if 最大 is not None and 值 > 最大:
        raise _参数不行(f"`{键}` 不能大于 {最大}（收到 {值}）。")
    return 值


def 要表(参, 键):
    值 = 参.get(键)
    if 值 is None:
        return []
    if isinstance(值, str):
        return [x.strip() for x in 值.replace("，", ",").split(",") if x.strip()]
    if isinstance(值, (list, tuple)):
        return [str(x).strip() for x in 值 if str(x).strip()]
    raise _参数不行(f"`{键}` 要字符串或字符串数组。")


