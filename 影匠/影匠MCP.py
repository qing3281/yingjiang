@包起来
def _工_审片(参):
    """机器审片。返回 PASS/FAIL + 必须修项 + 「机器算不了、需要人看」的清单。"""
    表, 错 = 装载()
    if 错:
        return 错

    戏名 = 要串(参, "戏名", 最长=80)
    阶段原 = 要串(参, "阶段", 最长=20)
    阶段 = 阶段别名.get(阶段原)
    if 阶段 is None:
        return 败(
            "没有这个阶段",
            f"阶段「{阶段原}」不认识。",
            建议="只能是：节拍 / 九宫格 / 四宫格 / 动态 / 成片（认 ①②③④、片 这些别名）。",
            可重试=True,
            下一步="查进度",
        )

    with 在戏里(戏名):
        # 审片.main 的退出码就是结论：0=PASS → 没有「必须修」；1=FAIL；2=用法错
        捕 = io.StringIO()
        try:
            with contextlib.redirect_stdout(捕), contextlib.redirect_stderr(捕):
                码 = 表["审片"].main(["审片.py", 戏名, 阶段])
        except SystemExit as e:
            码 = int(e.code or 0)
        except Exception as e:  # noqa: BLE001
            return 败(
                "审片崩了",
                f"{type(e).__name__}: {e}",
                建议="这是 审片.py 自己的 bug。把 说明 连同戏名/阶段报给用户。",
                可重试=False,
                回溯=traceback.format_exc()[-1000:],
            )

    结论 = {0: "PASS", 1: "FAIL", 2: "用法错"}.get(码, f"未知({码})")
    文本 = 捕.getvalue()

    # 分节：把 [机器判] 里的 ✓/✗/⚠ 行拆出来，AI 不用自己去啃文本
    必须修, 建议修, 通过 = [], [], []
    for 行 in 文本.splitlines():
        行 = 行.strip()
        if 行.startswith("✗ "):
            必须修.append(行[2:].strip())
        elif 行.startswith("⚠ "):
            建议修.append(行[2:].strip())
        elif 行.startswith("✓ "):
            通过.append(行[2:].strip())
    结论行 = next((l.strip() for l in 文本.splitlines() if l.strip().startswith("结论：")), "")

    return 成(
        数据={
            "戏名": 戏名,
            "阶段": 阶段,
            "结论": 结论,
            "结论行": 结论行,
            "必须修": 必须修,
            "建议修": 建议修,
            "通过项": 通过,
            "报告原文": 文本[-6000:],
        },
        下一步=(
            "阶段 PASS，可以进下一步（看 `查进度` 给的 下一步）。"
            if 码 == 0 else
            "先把「必须修」逐条改掉，改完重新 `审片` 同一阶段；改完产物要重出的走 `开镜`/`让镜动`。"
        ),
        提醒=(
            "机器判 PASS ≠ 片子好。「报告原文」末尾的「机器算不了、需要导演看的」那几项，"
            "必须交给用户或你自己真的去看图/看片。"
            if 码 == 0 else ""
        ),
    )


