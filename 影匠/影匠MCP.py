# ============================================================
# 一、输出通道：stdout 只走协议，别的全进收集器
# ============================================================

class 静音:
    """
    上下文管理器：把 stdout / stderr 全部吞掉。

    为什么必需：影匠的模块全是 `print`。MCP 的 stdout 是 JSON-RPC 通道，
    混进一行中文进度就会把宿主的解析器搞崩。所以凡是「调影匠的代码」
    都必须包在这层里 —— 没有例外。
    """

    def __init__(self, 也要抓stderr=True):
        self.要stderr = 也要抓stderr
        self.出 = io.StringIO()
        self.错 = io.StringIO()

    def __enter__(self):
        self._栈 = contextlib.ExitStack()
        self._栈.enter_context(contextlib.redirect_stdout(self.出))
        if self.要stderr:
            self._栈.enter_context(contextlib.redirect_stderr(self.错))
        return self

    def __exit__(self, *a):
        self._栈.close()
        return False

    def 文本(self):
        return self.出.getvalue()

    def 错文本(self):
        return self.错.getvalue()


class 报进度:
    """
    影匠的 `报=` 回调的替代品。

    `导演.开镜(..., 报=fn)` / `引擎.派工(..., 报=fn)` 会不停喊进度。
    把它接成这个收集器：不打印、只记账，最后原样交给 AI。
    """

    def __init__(self):
        self.行 = []

    def __call__(self, s):
        self.行.append(str(s))

    def 加上(self, 文本):
        """把一段被拦截的 stdout 也并进来（模块内部的 print）。"""
        for 行 in str(文本).splitlines():
            if 行.strip():
                self.行.append(行.strip())

    def 要(self, 最多=200):
        return self.行[-最多:]


# ============================================================
# 二、统一信封：成功 / 失败都从这里出
# ============================================================

def 成(数据=None, 日志=None, 下一步=None, **额外):
    """成功信封。`下一步` 是给 AI 的导航。"""
    果 = {"ok": True, "data": 数据 if 数据 is not None else {}}
    if 日志:
        果["日志"] = 日志
    if 下一步:
        果["下一步"] = 下一步
    果.update(额外)
    return 果


def 败(码, 说明, 建议="", 可重试=False, 下一步="", **额外):
    """
    失败信封。

    参数：
      码      机器可判别的短码（中文，见各工具）
      说明    人/模型可读，带上「现在是什么情况」
      建议    具体该怎么改
      可重试  True = 原样重发是安全的；False = 先查证，别重发
      下一步  建议调用的工具
    """
    果 = {
        "ok": False,
        "error": {
            "码": 码,
            "说明": 说明,
            "建议": 建议,
            "可重试": bool(可重试),
            "下一步": 下一步,
        },
    }
    果["error"].update(额外)
    return 果


# ============================================================
# 三、模块装载（带 stdout 拦截 + 结构化失败）
# ============================================================

_模块表 = {}
_装载过 = False


def 装载():
    """
    把影匠的模块 import 进来。只需要成功一次。

    返回 (模块表, 错误信封或 None)。
    import 失败不抛异常 —— 要变成结构化错误，让 AI 知道是环境问题还是代码问题。
    """
    global _装载过
    if _装载过:
        return _模块表, None

    if 这里 not in sys.path:
        sys.path.insert(0, 这里)

    缺 = []
    for 名 in ("引擎", "风格库", "角色库", "导演", "剧组", "审片"):
        try:
            # import 期间模块可能就 print（例如建目录、报告版本），一律拦掉
            with 静音() as 哑:
                _模块表[名] = __import__(名)
            if 哑.文本().strip():
                _模块表.setdefault("_装载噪音", []).append(哑.文本().strip())
        except Exception as e:  # noqa: BLE001 —— 这里就是要兜住一切
            缺.append({"模块": 名, "错": f"{type(e).__name__}: {e}"})

    if 缺:
        首个 = 缺[0]
        return _模块表, 败(
            "环境不可用",
            f"影匠模块装载失败：{首个['模块']} —— {首个['错']}",
            建议=(
                f"1) 确认 {这里} 下有 引擎.py/风格库.py/角色库.py/导演.py/剧组.py/审片.py；"
                "2) 用 ComfyUI 那个 venv 的 python 跑本服务器（它有 torch/PIL/numpy）；"
                "3) 单独跑一次 `python -c \"import 引擎\"` 看真实报错。"
            ),
            下一步="",
            全部失败=缺,
        )

    _装载过 = True
    return _模块表, None


def 导演模块(果=None):
    """拿 `导演` 模块；拿不到就返回 (None, 错误信封)。"""
    表, 错 = 装载()
    if 错:
        return None, 错
    return 表["导演"], None


