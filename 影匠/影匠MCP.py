# 错误码（JSON-RPC 标准）
解不出 = -32700        # Parse error
请求不对 = -32600      # Invalid Request
没这个方法 = -32601    # Method not found
参数不对 = -32602      # Invalid params
内部错 = -32603        # Internal error

协议_v = 缺省协议


def 写一帧(对象):
    """
    往 stdout 写一行 NDJSON。

    两个细节：
      · `ensure_ascii=False` —— 中文直出，宿主读日志时人能看懂。
      · 转义 U+2028/U+2029 —— 它们在某些客户端的按行解析里会被当成换行，
        把一条 JSON 劈成两半。这是线上真的踩过的坑。
      · flush —— stdio 管道不带行缓冲，不 flush 宿主就永远收不到。
    """
    文 = json.dumps(对象, ensure_ascii=False)
    文 = 文.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    sys.stdout.write(文 + "\n")
    sys.stdout.flush()


def 回结果(号, 果):
    写一帧({"jsonrpc": "2.0", "id": 号, "result": 果})


def 回错误(号, 码, 说明, 数据=None):
    错 = {"code": 码, "message": 说明}
    if 数据 is not None:
        错["data"] = 数据
    写一帧({"jsonrpc": "2.0", "id": 号, "error": 错})


def 工具内容(信封):
    """
    把工具信封包成 MCP 的 `content`。

    MCP 约定：工具的业务失败**不算协议错误**，而是 `isError:true` + 正常 result。
    所以影匠的「没有这部戏」走这里，而不是 JSON-RPC error ——
    这样 AI 能拿到完整的结构化错误体去决定下一步。
    """
    return {
        "content": [{"type": "text", "text": json.dumps(信封, ensure_ascii=False, indent=1)}],
        "isError": not 信封.get("ok", False),
    }


def 处理(消息):
    """处理一条 JSON-RPC 消息。返回 None 表示这是通知（不回）。"""
    global 协议_v

    if not isinstance(消息, dict) or 消息.get("jsonrpc") != "2.0":
        回错误(None, 请求不对, "不是合法的 JSON-RPC 2.0 消息（jsonrpc 必须是 \"2.0\"）。")
        return

    方法 = 消息.get("method")
    号 = 消息.get("id")
    参 = 消息.get("params") or {}
    if 参 is None:
        参 = {}
    if not isinstance(参, dict):
        参 = {}

    # 通知（没有 id）：绝不产生业务效果
    if 号 is None:
        return

    if not isinstance(方法, str) or not 方法:
        回错误(号, 请求不对, "缺少 method。")
        return

    # ---- 协议握手 ----
    if 方法 == "initialize":
        要的 = 参.get("protocolVersion")
        协议_v = 要的 if 要的 in 认识协议 else 缺省协议
        回结果(号, {
            "protocolVersion": 协议_v,
            "capabilities": {"tools": {"listChanged": False}},
            "serverInfo": {
                "name": 服务器名,
                "version": 服务器版本,
                "title": "影匠 · 本地 AI 影视流水线",
            },
            "instructions": 使用准则,
        })
        return

    if 方法 == "ping":
        回结果(号, {})
        return

    if 方法 == "tools/list":
        回结果(号, {"tools": 工具表})
        return

    if 方法 == "tools/call":
        名 = 参.get("name")
        实参 = 参.get("arguments") or {}
        if not isinstance(名, str) or 名 not in 注册表:
            回错误(号, 参数不对, f"不认识这个工具：{名!r}",
                   数据={"可用工具": list(注册表.keys())})
            return
        if not isinstance(实参, dict):
            return 回结果(号, 工具内容(败("参数不对", "arguments 必须是一个对象。")))
        try:
            信封 = 注册表[名](实参)
        except Exception as e:  # noqa: BLE001 —— 最外层兜底，服务器绝不能死
            信封 = 败(
                "内部出错",
                f"{type(e).__name__}: {e}",
                建议="本服务器自己的 bug。请把 说明 和调用参数报给用户。",
                可重试=False,
                回溯=traceback.format_exc()[-1200:],
            )
        回结果(号, 工具内容(信封))
        return

    # 客户端取消通知之外的未知方法
    回错误(号, 没这个方法, f"不支持的方法：{方法}")


# ============================================================
# 九、主循环：stdio NDJSON
# ============================================================

最大请求字节 = 1024 * 1024   # 1 MiB，超了直接拒，防止被一条畸形消息拖死


def 主():
    """
    从 stdin 逐行读 JSON-RPC，写到 stdout。

    为什么不用 `for line in sys.stdin`：那会走 Python 的预读缓冲，
    在某些宿主的交互式管道下会攒着不吐。用显式 readline + 手动 flush 更稳。
    """
    # 启动自检：模块装载失败也照样起来 —— 让 AI 从 tools/call 拿到结构化错误，
    # 而不是面对一个「服务器没反应」的黑盒。
    _, 装载错 = 装载()
    if 装载错:
        sys.stderr.write("[影匠MCP] 警告：影匠模块装载失败，工具会返回结构化错误。\n")
        sys.stderr.write(f"[影匠MCP] {装载错['error']['说明']}\n")
        sys.stderr.write("[影匠MCP] 修好环境后重启本服务器即可。\n")
    else:
        sys.stderr.write(f"[影匠MCP] 就绪 · {len(工具表)} 个工具 · 影匠目录 {这里}\n")
    sys.stderr.flush()

    输入 = sys.stdin
    while True:
        try:
            行 = 输入.readline()
        except (KeyboardInterrupt, EOFError):
            break
        except Exception as e:  # noqa: BLE001
            sys.stderr.write(f"[影匠MCP] 读 stdin 出错：{e}\n")
            break

        if not 行:      # EOF —— 宿主关闭了管道
            break
        行 = 行.strip()
        if not 行:
            continue
        # 有些 shell（Windows PowerShell 的 echo 就是）会带 UTF-8 BOM
        if 行.startswith("\ufeff"):
            行 = 行.lstrip("\ufeff")

        if len(行.encode("utf-8")) > 最大请求字节:
            回错误(None, 请求不对, f"请求超过 {最大请求字节 // 1024 // 1024} MiB 上限，已丢弃。")
            continue

        try:
            消息 = json.loads(行)
        except json.JSONDecodeError as e:
            回错误(None, 解不出, f"JSON 解析失败：{e.msg}（第 {e.colno} 列）")
            continue

        try:
            处理(消息)
        except Exception as e:  # noqa: BLE001 —— 单条消息出问题不能拖垮整个连接
            sys.stderr.write(f"[影匠MCP] 处理消息异常：{type(e).__name__}: {e}\n")
            try:
                回错误(消息.get("id") if isinstance(消息, dict) else None,
                       内部错, f"{type(e).__name__}: {e}")
            except Exception:  # noqa: BLE001
                pass

    sys.stderr.write("[影匠MCP] stdin 关闭，退出。\n")
    sys.stderr.flush()
    return 0


if __name__ == "__main__":
    try:
        sys.exit(主())
    except KeyboardInterrupt:
        sys.exit(0)
