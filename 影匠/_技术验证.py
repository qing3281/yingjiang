# -*- coding: utf-8 -*-
"""技术验证：分镜模型能不能在一格里画出「指定的两个不同的人」。

这是新片子最大的技术风险。上一部《雪线》只有凌霜一个人，所以没暴露。
这一部有四个角色、要同框、要打得起来 —— 如果模型一给两个锚点就糊成
「两个人长得一模一样」，那整个分镜法就得换。

验证三件事：
  甲、**两个锚点同框** —— 各画各的，还是糊成一个人 / 一张脸复制两份？
  乙、**打斗动作** —— 刀锋横扫这种大动态，4.56 秒的段能不能接住？
  丙、**背影/远景里认不认得出人** —— 远景不喂锚点，靠提示词能不能立住。

产物落在 `作品\\_技术验证\\`，不动任何正式目录。
"""
import os
import sys
import time

根 = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, 根)

import 导演      # noqa: E402
import 角色库    # noqa: E402

出 = os.path.join(根, "作品", "_技术验证")
os.makedirs(出, exist_ok=True)
宽, 高 = 1344, 768
种子 = 20261014


def 报(s):
    print(s, flush=True)


def 立两个测试角色():
    """两个外形差异拉到最大的角色 —— 差异越大，糊在一起时越容易看出来。"""
    角色库.建("甲客", 性别="男", 年龄="中年", 发="灰白短发贴着头皮",
              肤="古铜色", 眼="细长鹰眼", 服="深灰色粗布短打，腰缠麻绳",
              特征="右脸一道从眉骨到下巴的旧疤", 体态="矮壮敦实", 种子=20261014)
    角色库.建("乙客", 性别="女", 年龄="青年", 发="乌黑高马尾束到脑后",
              肤="苍白", 眼="大而圆的褐色眼睛", 服="月白色窄袖劲装，腰束银扣皮带",
              特征="左耳挂一枚银环", 体态="纤细高挑", 种子=20261015)
    报("  两个测试角色已登记：甲客 / 乙客")


def 跑(名, 词, 角色, 高, 宽, 动作=None):
    t = time.time()
    r = 导演.开镜(词, 风格="cinematic-real", 角色=角色, 种子=种子,
                  宽=1344, 高=768, 文件名=名, 用定妆照=False)
    路 = r.get("路", "")
    报(f"  ✓ {os.path.basename(路)}  {time.time()-t:.1f} 秒")
    return 路


def main():
    立两个测试角色()
    导演.立戏("_技术验证", 默认风格="cinematic-real", 默认角色=["甲客", "乙客"])

    报("\n【甲】两个锚点同框 —— 中景，两人对峙")
    跑("甲_双人中景",
      "medium shot。一间昏暗的旧客栈堂屋，一张翻倒的方桌。画面左边站着一个矮壮敦实的中年"
      "男人，灰白短发贴着头皮，古铜色的皮肤，右脸一道从眉骨到下巴的旧疤，深灰色粗布短打，"
      "腰缠麻绳。画面右边站着一个纤细高挑的年轻女人，乌黑高马尾束到脑后，皮肤苍白，"
      "褐色的大圆眼，左耳挂一枚银环，月白色窄袖劲装，腰束银扣皮带。两人相隔三步，"
      "相对而立，都没有动。油灯从侧面照过来，暖黄与深褐，空气里飘着尘。",
      ["甲客", "乙客"], 高, 宽)

    报("\n【乙】打斗大动态 —— 刀锋横扫")
    跑("乙_刀锋横扫",
      "medium close-up。一个矮壮敦实的中年男人，灰白短发贴着头皮，古铜色的皮肤，"
      "右脸一道从眉骨到下巴的旧疤，深灰色粗布短打，正抡起一把单刀横向扫出。"
      "刀身在画面里拉出一道模糊的银弧，刀刃上方带起一线细碎的血珠和灰尘。"
      "他的身体因为发力而扭转，重心压得很低。背景是一堵斑驳的土墙，"
      "冷青色的天光从门口斜切进来。强烈的运动模糊。",
      ["甲客"], 高, 宽)

    报("\n【丙】远景不喂锚点 —— 靠提示词立人")
    跑("丙_远景立人",
      "extreme wide shot。一条积雪的长街，两侧是低矮的木屋檐，屋檐下垂着冰锥。"
      "街心偏左的位置走着一个矮壮敦实的中年男人，灰白短发，深灰色粗布短打，"
      "手里提着一把刀，走得很慢。街面上一行脚印从他身后一直排到画面深处。"
      "街上再没有别人。冷青灰的天光压得很平，整幅画几乎没有暖色。",
      [], 高, 宽)

    报(f"\n产物在 {出}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
