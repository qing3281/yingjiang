def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("戏")
    ap.add_argument("--空跑", action="store_true")
    参 = ap.parse_args()

    路 = os.path.join(根, "作品", 参.戏, "02-九宫格.md")
    if not os.path.exists(路):
        print(f"✗ 找不到 {路}")
        return 1

    文 = open(路, encoding="utf-8").read()
    行表 = 文.split("\n")
    出 = []
    当前格 = None
    插了 = []
    有 = 0

    for 行 in 行表:
        m = re.match(r"^##\s*格\s*(\d+)\s*(?:——|--|—)", 行)
        if m:
            当前格 = int(m.group(1))
        出.append(行)
        # 紧跟在「提示词：」那一行之后插入「动作：」
        if 当前格 and re.match(r"^-\s*提示词\s*[:：]", 行):
            动 = 动作表.get(当前格)
            if 动:
                出.append(f"- 动作：{动}")
                插了.append(当前格)

    # 统计原本已有的（避免重复插入）
    有 = len(re.findall(r"^-\s*动作\s*[:：]", 文, flags=re.M))
    if 有:
        print(f"⚠ 文件里已经有 {有} 处『动作：』，本次插入 {len(插了)} 处 —— "
              f"可能会重复。先手工清一下再跑。")
        return 1

    print(f"将插入 {len(插了)} 格的动作：{插了}")
    if len(插了) != 45:
        print(f"⚠ 期望 45 格，实际 {len(插了)} 格")

    if 参.空跑:
        return 0

    import shutil
    shutil.copyfile(路, 路.replace(".md", ".md.bak"))
    open(路, "w", encoding="utf-8").write("\n".join(出))
    print(f"✓ 写好 {路}（原文件备份成 02-九宫格.md.bak）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
