def 看风格(关键词=""):
    风格库.打印全部() if not 关键词 else None
    if 关键词:
        for k, 中, 用 in 风格库.找(关键词):
            print(f"  {k:<18} {中:<10} {用}")


def 看角色():
    角色库.打印()


