# -*- coding: utf-8 -*-
"""给《觉醒》六个说话人挑音色（第二版：加硬闸门）。

## 第一版为什么差点选错

第一版纯按文件名关键词打分，结果：

- **阿棠** 首选 `偏萝莉的少女音.wav` —— 名字最贴，但一解码：**峰值 0.064、有效值 0.0062**。
  正常音色峰值 0.7~0.9。**这是个几乎没人声的文件**，拿它做 IndexTTS 的克隆参考
  只会克隆出一片噪声。*文件名说它好听，文件本身没说话。*
- **内门执事** 首选 `专业、播音腔的中年女声新闻解说.mp3` —— 名字分最高，
  但内门执事是**男的**。库里没有性别字段（967 条空），名字却是硬证据。

## 这一版的闸门

1. **硬闸门**（不过就扔）：能解码、`秒 ≥ 2.0`、`峰值 ≥ 0.20`、`有效值 ≥ 0.012`
2. **性别闸门**：角色的性别是硬的，按文件名里的「男 / 女 / 少女 / 萝莉 / 御姐 / 大叔」判
3. 再按关键词打分，**并列时选峰值高的**（峰值高 = 录音离麦近 = 克隆更稳）

闸门的量都来自 soundfile 真解码，不来自名字。
"""
import json
import os
import sys

根 = os.path.dirname(os.path.abspath(__file__))
库路 = os.path.join(根, "音色", "音色库.json")
映射路 = os.path.join(根, "音色", "角色映射.json")

# 硬闸门
最短秒 = 2.0
最小峰值 = 0.20
最小有效值 = 0.012

女词 = ["女", "少女", "萝莉", "御姐", "姐", "妈", "婶", "婆婆", "姑娘", "妹"]
男词 = ["男", "大叔", "爷", "伯", "哥", "爸", "叔"]

想找 = {
    "陈老根": (男词, ["老年", "沧桑", "苍老", "老人", "沙哑", "低沉"],
             "六十八岁，扫了四十年地。声音得是**用旧了的**：沙、慢、不响，"
             "但不是可怜相 —— 他全片没有一句是求人的。"),
    "系统": (男词, ["机械", "电子", "机器人", "AI", "合成", "播报"],
           "灵脉勘录残页。不解释、不动情，只报数。声音要**没有温度**，"
           "跟其他任何人都不像。"),
    "阿棠": (女词, ["少女", "萝莉", "童", "女童", "小女孩", "清脆", "甜美"],
           "十五六岁，全片唯一的暖。她是唯一一个问老根名字的人。"),
    "周执": (男词, ["中年", "沉稳", "磁性", "权威", "信服", "官"],
           "四十几岁外门掌事。表面官面文章，底下压了二十年的心事。"
           "要有**体面**，不能一听就是坏人。"),
    "内门执事": (男词, ["旁白", "解说", "沉稳", "中年", "磁性"],
              "只出现一两次的功能性角色 —— **必须是男的**（第一版错挑了个女声）。"),
    "旁白": (男词, ["磁性悬疑", "解说", "沉稳", "磁性", "故事"],
           "全片只有两句（格1 与格74），是题眼。要一把**能压住整个片子**的嗓子。"),
}


def 验(路):
    try:
        import soundfile as sf
        import numpy as np
        x, sr = sf.read(路, always_2d=True)
        if x.size == 0:
            return None
        m = x.mean(axis=1)
        return {"秒": len(m) / sr, "采样": sr, "声道": x.shape[1],
                "峰值": float(np.abs(m).max()),
                "有效值": float(np.sqrt((m ** 2).mean()))}
    except Exception:
        return None


def 过闸(实测):
    if not 实测:
        return False, "解不开"
    if 实测["秒"] < 最短秒:
        return False, f"只有 {实测['秒']:.1f} 秒"
    if 实测["峰值"] < 最小峰值:
        return False, f"峰值 {实测['峰值']:.3f} → 几乎是静音"
    if 实测["有效值"] < 最小有效值:
        return False, f"有效值 {实测['有效值']:.4f} → 几乎是静音"
    return True, ""


def 判性别(名):
    if any(w in 名 for w in 女词):
        return "女"
    if any(w in 名 for w in 男词):
        return "男"
    return "?"


音频 = json.load(open(库路, encoding="utf-8"))["音频"]
映射 = json.load(open(映射路, encoding="utf-8")) if os.path.isfile(映射路) else {"角色": {}}
映射.setdefault("角色", {})

print(f"音色库 {len(音频)} 条　硬闸门：≥{最短秒}s / 峰值≥{最小峰值} / 有效值≥{最小有效值}\n")

结果 = {}
for 角, (性词, 关键词, 理由) in 想找.items():
    要 = "女" if 性词 is 女词 else "男"
    过 = []
    砍 = {"性别不对": 0, "解不开": 0, "太短": 0, "静音": 0}
    for t in 音频:
        名 = (t.get("文件名") or "") + " " + str(t.get("名字") or "")
        g = 判性别(名)
        if g != "?" and g != 要:
            砍["性别不对"] += 1
            continue
        路 = t.get("路径") or ""
        实测 = 验(路)
        ok, 因 = 过闸(实测)
        if not ok:
            砍["解不开" if 因 == "解不开" else ("太短" if "秒" in 因 else "静音")] += 1
            continue
        分 = sum(10 - i for i, k in enumerate(关键词) if k in 名)
        if g == "?":
            分 -= 2          # 性别没在名字里体现，稍微降一点
        过.append((分, 实测["峰值"], 名.strip(), 路, 实测))

    过.sort(key=lambda z: (-z[0], -z[1]))
    print(f"▌ {角}（要{要}声）")
    print(f"    砍掉 {砍}　剩 {len(过)} 条")
    for 分, 峰, 名, 路, 实测 in 过[:3]:
        print(f"    {分:>3}分 峰值{峰:.2f}  {实测['秒']:.1f}s {实测['采样']}Hz  {名[:52]}")
    if 过:
        分, 峰, 名, 路, 实测 = 过[0]
        结果[角] = {"音色": 路, "名字": 名, "理由": 理由,
                  "实测": {k: round(v, 4) for k, v in 实测.items()}}
        print(f"    → 定：{名[:56]}\n")
    else:
        print(f"    → 过闸的一条都没有！\n")

映射["角色"].update(结果)
json.dump(映射, open(映射路, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
print(f"已写 {映射路}")
print(f"《觉醒》六个说话人：{list(结果)}")
缺 = [k for k in 想找 if k not in 结果]
if 缺:
    print(f"⚠ 没定下来的：{缺}")
