# -*- coding: utf-8 -*-
"""把「眼下两片青黑的眼袋」改成不会画成黑眼圈的说法。

问题：原句在 30 格里逐字复用，模型把它画成**眼睛周围一整块很重的黑**，
看着像被人打青了眼睛，而 00-故事.md 写的是「眼窝深陷，眼下两片青黑的眼袋」
—— 意思是年纪大了的自然眼袋，不是伤。

改法：把「色」说成「袋」——加「年纪大了的自然眼袋」「不是黑眼圈、不是伤」
两道否定，并把「两片青黑」降成「浅浅的青灰色」。
"""
import io
import os
import sys

根 = os.path.dirname(os.path.abspath(__file__))
分镜 = os.path.join(根, "作品", "觉醒", "02-九宫格.md")
故事 = os.path.join(根, "作品", "觉醒", "00-故事.md")

旧 = "眼窝深陷，眼下两片青黑的眼袋，左边眼珠比右边清亮一点"
新 = ("眼窝深陷，眼下只有两道老年人常见的、浅浅的青灰色眼袋"
      "（是年纪大了皮松出来的袋，不是黑眼圈、不是淤青、不是伤），"
      "左边眼珠比右边清亮一点")

# 几句话短一点的写法（00-故事.md 里的字段）
旧短 = "眼窝深陷，眼下两片青黑的眼袋；左边眼珠比右边清亮一点"
新短 = ("眼窝深陷，眼下只有两道浅浅的青灰色眼袋（年纪大了皮松出来的袋，"
        "不是黑眼圈、不是淤青、不是伤）；左边眼珠比右边清亮一点")

# 「眼下的眼袋青黑」这种省略写法
旧省 = "眼窝深陷，眼下的眼袋青黑"
新省 = "眼窝深陷，眼下有两道浅浅的青灰色眼袋（不是黑眼圈、不是淤青、不是伤）"


def 换(路):
    t = io.open(路, encoding="utf-8").read()
    原 = t
    计 = {}
    for a, b in ((旧, 新), (旧短, 新短), (旧省, 新省)):
        n = t.count(a)
        if n:
            t = t.replace(a, b)
            计[a[:12]] = n
    if t != 原:
        io.open(路, "w", encoding="utf-8").write(t)
    return 计, len(原), len(t)


for p in (分镜, 故事):
    if not os.path.isfile(p):
        print(f"  ✗ 没有 {p}")
        continue
    计, 前, 后 = 换(p)
    print(f"{os.path.basename(p)}：{sum(计.values())} 处  ({前} → {后} 字节)")
    for k, v in 计.items():
        print(f"    {k}…  ×{v}")

# 复验：旧的句子应当一处不剩
t = io.open(分镜, encoding="utf-8").read()
剩 = t.count(旧) + t.count(旧短) + t.count(旧省)
print(f"\n复验：分镜里旧句还剩 {剩} 处（应为 0）")
print(f"      新句出现 {t.count('浅浅的青灰色眼袋')} 次")
sys.exit(1 if 剩 else 0)
