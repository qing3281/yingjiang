def _钥匙():
    """从 DSH 的凭据文件里拿 DeepSeek key。

    ★ 跟 `_控台.py` 的 `_钥匙()` **同一个文件、同一个正则** —— 两边不一致的话，
      控台能写剧本、命令行不能（或者反过来），最难查。
      实际路径就是 `D:\\DSH\\home\\.credentials.yaml`。自己再存一份 = 以后轮换时两处不一样。
    """
    候选 = [
        r"D:\DSH\home\.credentials.yaml",
        os.path.join(os.environ.get("DSH_HOME", r"D:\DSH\home"), ".credentials.yaml"),
        os.path.join(os.environ.get("DSH_HOME", r"D:\DSH\home"), "credentials.yaml"),
    ]
    for p in 候选:
        if not p or not os.path.exists(p):
            continue
        try:
            with open(p, encoding="utf-8") as f:
                文 = f.read()
        except Exception:
            continue
        m = re.search(r"DEEPSEEK_API_KEY\s*:\s*[\"']?(sk-[A-Za-z0-9\-_]{10,})", 文)
        if m:
            return m.group(1)
    return os.environ.get("DEEPSEEK_API_KEY", "")


def 叫模型(提示, 超时=180, 温度=1.0, 上限=4000):
    """调 DeepSeek。失败要把原因原样带回来，不许静默。"""
    钥 = _钥匙()
    if not 钥:
        return {"ok": False, "错": "没找到 DEEPSEEK_API_KEY"}
    体 = json.dumps({
        "model": "deepseek-chat",
        "messages": [{"role": "user", "content": 提示}],
        "temperature": 温度,
        "max_tokens": 上限,
    }).encode()
    try:
        req = urllib.request.Request(
            "https://api.deepseek.com/v1/chat/completions", data=体,
            headers={"Authorization": "Bearer " + 钥, "Content-Type": "application/json"})
        r = json.loads(urllib.request.urlopen(req, timeout=超时).read().decode())
        return {"ok": True, "文": r["choices"][0]["message"]["content"].strip(),
                "用": r.get("usage", {})}
    except Exception as e:
        return {"ok": False, "错": "%s: %s" % (type(e).__name__, str(e)[:300])}


