def 拼成一本(戏名, 梗概, 人物, 分场, 台词):
    return """# 剧本 · {戏}

{梗概}

## 主要人物

{人物}

## 分场

{分场}

## 台词

{台词}
""".format(戏=戏名, 梗概=梗概.strip(), 人物=人物.strip(),
           分场=分场.strip(), 台词=台词.strip())


def 四步全跑(素材, 戏名="未命名", 套路="", 人数=2, 秒=90, 报=None):
    """
    一口气跑完四步 —— **给「我要看结果」用，不是给「我要审」用**。
    真要审的时候一步一停，用上面那四个函数。

    返回 {ok, 本, 各步, 自检, 秒}
    """
    报 = 报 or (lambda s: print("   " + s, flush=True))
    t0 = time.time()
    各 = {}
    报("第 1 步 · 梗概…")
    r = 第一步_梗概(素材, 套路, 人数=人数)
    if not r["ok"]:
        return {"ok": False, "错": "梗概没写出来：" + r["错"], "各步": 各}
    各["梗概"] = r["文"]
    报("   走的结构：%s（%s）" % (r["套路"], r["为什么"]))

    报("第 2 步 · 人物…")
    r2 = 第二步_人物(各["梗概"], 人数)
    if not r2["ok"]:
        return {"ok": False, "错": "人物没写出来：" + r2["错"], "各步": 各}
    各["人物"] = r2["文"]

    报("第 3 步 · 分场…")
    r3 = 第三步_分场(各["梗概"], 各["人物"], r["套路"], 秒)
    if not r3["ok"]:
        return {"ok": False, "错": "分场没分出来：" + r3["错"], "各步": 各}
    各["分场"] = r3["文"]

    报("第 4 步 · 台词…")
    r4 = 第四步_台词(各["分场"])
    if not r4["ok"]:
        return {"ok": False, "错": "台词没写出来：" + r4["错"], "各步": 各}
    各["台词"] = r4["文"]

    本 = 拼成一本(戏名, 各["梗概"], 各["人物"], 各["分场"], 各["台词"])
    报("自检…")
    查 = 自检(本)
    for x in 查["问题"]:
        报("   ⚠ " + x)
    if 查["过"]:
        报("   ✓ 自检过了：%d 场 / %d 人 / %d 句台词 / 最长 %d 字"
           % (查["数字"]["场数"], 查["数字"]["人物数"],
              查["数字"]["台词句数"], 查["数字"]["最长台词"]))
    return {"ok": True, "本": 本, "各步": 各, "自检": 查,
            "套路": r["套路"], "秒": round(time.time() - t0, 1)}


