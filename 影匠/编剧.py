def _带补(提示, 补):
    """自检挑出的毛病，喂回给模型 —— 明说病名，重跑才不是抽奖。"""
    if not 补:
        return 提示
    return (提示 + chr(10) + chr(10)
            + "★ 上一版没过，问题是：**" + str(补) + "**" + chr(10)
            + "这一版必须把这个改掉，别的地方照旧。" + chr(10))


