def _切段(整本):
    """
    把一份剧本按 `## 标题` 切成 {标题: 正文}。

    ★ 为什么要先切段：第一版 `自检()` 用一条正则满篇扫，结果
      **把「## 分场」下面那 5 个 `### 第 N 场` 和「## 台词」下面那 5 个
      `### 第 N 场` 数成了同一个东西**，报出「分了 10 场」；
      又把 `- **变化**：…` 当成台词量，报出「最长一句 54 个字」。
      满篇扫的判据 = 假判据（这个病我犯过 11 次）。分好段再数。
    """
    段 = {}
    现 = None
    for 行 in 整本.split("\n"):
        m = re.match(r"^##\s+(.+?)\s*$", 行)
        if m:
            现 = m.group(1).strip()
            段[现] = []
            continue
        if 现 is not None:
            段[现].append(行)
    return {k: "\n".join(v) for k, v in 段.items()}


def _找段(段, *关键词):
    """按关键词找一段 —— 标题是模型写的，可能叫「主要人物」「人物」「人物设定」"""
    for k, v in 段.items():
        for w in 关键词:
            if w in k:
                return v
    return ""


def 自检(整本):
    """
    拿一份写好的剧本过一遍，返回 {过: bool, 问题: [...], 数字: {...}}。

    ★ 这个函数**只挑毛病，不改东西** —— 改不改由他定。
    ★ 数数一律**先分好段再数**，不许满篇正则扫（见 `_切段` 的注释）。
    """
    问 = []
    n = {}
    段 = _切段(整本)

    人段 = _找段(段, "人物", "角色")
    场段 = _找段(段, "分场", "场次")
    台段 = _找段(段, "台词", "对白")

    # --- 场 ---
    场 = re.findall(r"^###\s*第\s*(\d+)\s*场", 场段, re.M)
    n["场数"] = len(场)
    if n["场数"] == 0:
        问.append("一场都没分出来（「## 分场」那一节里没有 `### 第 N 场`）")
    elif n["场数"] < 5:
        问.append("只分了 %d 场 —— 太少，故事转不开（5–9 场才对）" % n["场数"])
    elif n["场数"] > 9:
        问.append("分了 %d 场 —— 太多，1–3 分钟的片装不下（5–9 场才对）" % n["场数"])

    # 每场的「变化」
    变 = re.findall(r"变化[*＊]*\s*[：:]\s*(.+)", 场段)
    变 = [x.strip().strip("*") for x in 变 if x.strip().strip("*")]
    n["写了变化的场数"] = len(变)
    if n["场数"] and len(变) < n["场数"]:
        问.append("%d 场里只有 %d 场写了「变化」—— 没写变化的那几场等于没戏"
                  % (n["场数"], len(变)))
    重 = {}
    for x in 变:
        k = re.sub(r"[\s，。、,.；;：:\"'“”]", "", x)[:14]
        重[k] = 重.get(k, 0) + 1
    印 = [k for k, v in 重.items() if v > 1 and k]
    if 印:
        问.append("有 %d 场的「变化」写重了：%s" % (len(印), "、".join(印[:3])))

    # --- 人 ---
    #
    # ★ 人物标题的层级是模型自己定的：实测 deepseek 写的是
    #     `## 主要人物` 空一节，紧接着 `## 老陈（六十七岁，修鞋匠）` —— 人物是 **## 级**，
    #   跟「分场」「台词」平级。所以不能按层级找，只能**按名字排除固定的那几节**。
    固定节 = ("主要人物", "人物", "角色", "人物设定", "分场", "场次", "台词", "对白",
             "一句话故事", "故事", "梗概", "戏眼", "落点")
    人 = [k for k in 段 if not any(w in k for w in 固定节)]
    # 兜底：万一模型把人物写在 `###` 里（在「主要人物」那一节内）
    if not 人:
        人 = [x.strip() for x in re.findall(r"^###?\s*([^\n#]+)$", 人段, re.M)
             if x.strip() and "第" not in x[:3]]
    n["人物数"] = len(人)
    n["人物"] = 人
    if n["人物数"] < 2:
        问.append("只认出 %d 个人物 —— 至少要有 2 个人才有对手戏（认到的：%s）"
                  % (n["人物数"], "、".join(人[:4]) or "无"))
    人正文 = "\n".join(段[k] for k in 人) or 人段
    认 = len(re.findall(r"一眼能认出来", 人正文))
    n["写了识别特征的"] = 认
    if n["人物数"] and 认 < n["人物数"]:
        问.append("「一眼能认出来的东西」只写了 %d 个，有 %d 个人物没有 —— 这是锁脸的关键，必须有"
                  % (认, n["人物数"] - 认))
    性 = [w for w in ("善良", "倔强", "温柔", "孤僻", "乐观", "内向", "开朗", "坚强") if w in 人正文]
    if 性:
        问.append("人物里写了性格形容词：%s —— 性格要靠样子看出来，不是写出来" % "、".join(性))

    # --- 台词 ---
    场块 = re.split(r"^###\s*第\s*\d+\s*场", 台段, flags=re.M)[1:]
    句 = []
    空场 = 0
    谁在说 = []          # ★ 记下每一句是谁说的 —— 用来查「有名有姓的人一句都没有」
    for b in 场块:
        if "无台词" in b:
            空场 += 1
            continue
        for 行 in b.split("\n"):
            行 = 行.strip()
            if not 行.startswith(("-", "*")):
                continue
            t = re.sub(r"^[-*]\s*", "", 行)
            _m = re.match(r"^([^：:]{1,12})[：:]", t)      # 「老陈：」 → 记下老陈
            if _m:
                谁在说.append(_m.group(1).strip())
            t = re.sub(r"^[^：:]{1,12}[：:]", "", t)      # 去掉「老陈：」
            t = re.sub(r"[（(].*?[)）]", "", t)            # 去掉（手上的动作）
            t = t.strip()
            if t:
                句.append(t)
    n["台词句数"] = len(句)
    n["无台词场数"] = 空场
    n["最长台词"] = max((len(x) for x in 句), default=0)

    if n["台词句数"] > 12:
        问.append("台词 %d 句 —— 超过 12 句了" % n["台词句数"])
    if n["最长台词"] > 18:
        长 = max(句, key=len)
        问.append("最长一句台词 %d 个字 —— 超过 18 字了：「%s」" % (n["最长台词"], 长[:30]))
    if 空场 < 2:
        问.append("只有 %d 场没有台词 —— 要求至少 2 场（全片都在说话就变成广播剧了）" % 空场)
    if n["场数"] and n["台词句数"] == 0:
        问.append("一句台词都没有（第 4 步可能没跑）")

    # ★ 有名有姓的人，不能一句都不说 —— 实战踩到：耶梦加得（龙）从头到尾零台词，
    #   自检却报「过」；只看句数的检查量不出「谁没说」。
    #   例外：故意不说话的（哑巴/婴儿/动物/旁白型）就在人物描述里写「不说话」三个字。
    净名 = [re.split(r"[（(]", k)[0].strip() for k in 人]
    哑的 = [k for k in 人 if "不说话" in k]
    句都没 = [a for a in 净名 if a and a not in 谁在说
             and not any(a in x for x in 哑的)]
    n["不说话的"] = 句都没
    if len(净名) >= 2 and 句都没:
        问.append("%s 一句台词都没有 —— 两个人斗了 8 场，对面不能是块石头"
                  "（真不会说话就写在人物描述里加「不说话」三个字）" % "、".join(句都没))

    # --- ★ 戏眼要早立 ---
    #
    # ★ 这条尺子不是我发明的，是他 10-15 立的：
    #     「核心矛盾（那句话转的那个词）第一次出现的位置 ÷ 全片时长 > 30% 就是没讲清，
    #      不用等你说。」
    #   片子上的量法在 `_量核心矛盾.py`（按秒）；**这里按场次折算同一条尺子** ——
    #   剧本阶段就该拦住，别等 8 小时出完片才发现。
    #   实战由来：《雪线》高潮那句「那就没有例外」落在 82.6%，而「例外」这个词在那之前
    #   一次都没出现过 —— 观众到 2:31 才第一次听见规矩是什么。
    m眼 = re.search(r"戏眼[：:]\s*(.+)", 整本)
    if m眼 and n["场数"]:
        眼 = m眼.group(1).strip()
        泛 = ("结果", "只能", "全靠", "已经", "一个", "他的", "她的", "然后", "因为", "所以",
              "没有", "不是", "就是", "一下", "起来", "出来", "只好", "到了", "这是", "还是",
              "却把", "反而", "只能把", "于是", "上去", "过来", "松开", "接住", "砍不中",
              "第一次", "第二次", "第三次")
        # ★ 先按标点切句，再把**所有 2–4 字的子串**都当候选。
        #   不能用 `[\u4e00-\u9fa5]{2,6}` 直接抓 —— 它是贪婪匹配，**会跨词**：
        #   实测把「楚子航全靠右手缠绷带去砍」抓成了「楚子航全靠右」，跟分场里
        #   一个字都对不上，于是每次都误报「戏眼是空的」。
        #   跨词抓不出真词，但**真词一定会作为子串出现**，所以改成「数它出现在几个小句里」。
        句s = [x for x in re.split(r"[，。、；;：:,]", 眼) if x.strip()]
        计数, 首次 = {}, {}
        位 = 0
        for 句 in 句s:
            此句 = set()
            for 长 in (4, 3, 2):
                for i in range(len(句) - 长 + 1):
                    块 = 句[i:i + 长]
                    if 块 in 泛 or not re.fullmatch(r"[\u4e00-\u9fa5]+", 块):
                        continue
                    if 块 in 此句:
                        continue
                    此句.add(块)
                    计数[块] = 计数.get(块, 0) + 1
                    首次.setdefault(块, 位)
            位 += 1
        # 人名不算关键东西（人一直在场，量他没有意义）
        for k in n.get("人物", []):
            名k = re.split(r"[（(]", k)[0].strip()
            计数.pop(名k, None)
        # 人名是子串时也要剔掉（「楚子航」会带出「楚子」「子航」）
        for k in list(计数):
            if any(k in re.split(r"[（(]", x)[0] for x in n.get("人物", [])):
                计数.pop(k, None)
        if 计数:
            # ★ 打分顺序（实测调出来的，别乱改）：
            #   ① **出现在分场正文里的优先** —— 这条判据问的就是「那个东西在分场里立起来了吗」，
            #      所以先认「确实在分场里出现过」的候选；
            #   ② 出现在越多小句里越像「那个东西」；
            #   ③ 并列时取长的（「青铜匕首」比「匕首」更像那个东西）；
            #   ④ 再并列取先出现的（戏眼的主语一般在前）。
            #   反测踩到的坑：只按 ②③④ 打分时，「那把青铜匕首从头到尾决定胜负」整句只有
            #   一个小句，所有候选都是 1 分，于是按最长挑了「那把青铜」—— 分场里写的是
            #   「青铜匕首」，对不上，误报「戏眼是空的」。
            要的 = max(计数, key=lambda k: (k in 场段, 计数[k], len(k), -首次.get(k, 99)))
            n["戏眼候选"] = sorted(计数, key=lambda k: (k not in 场段, -计数[k],
                                                      -len(k), 首次.get(k, 99)))[:5]
            块s = re.split(r"(?=^###\s*第\s*\d+\s*场)", 场段, flags=re.M)
            块s = [b for b in 块s if re.match(r"^###\s*第\s*\d+\s*场", b)]
            早 = max(1, round(n["场数"] / 3))
            出现 = [i + 1 for i, b in enumerate(块s) if 要的 in b]
            n["戏眼关键词"] = 要的
            n["戏眼第一次出现在第几场"] = 出现[0] if 出现 else 0
            n["最晚该在第几场"] = 早
            if not 出现:
                问.append("戏眼那个东西（「%s」）在分场里一次都没出现 —— 戏眼是空的" % 要的)
            elif 出现[0] > 早:
                问.append("戏眼那个东西（「%s」）到第 %d 场才第一次出现 —— 前 %d 场观众不知道"
                          "这片子在讲什么（他的尺子：核心矛盾落在前 1/3，也就是第 %d 场以前）"
                          % (要的, 出现[0], 早, 早))

    # --- 禁词 ---
    脏 = [w for w in 禁词 if w in 整本]
    if 脏:
        问.append("出现了文学腔的词：%s" % "、".join(脏))

    # --- 落点看得见吗 ---
    m = re.search(r"落点[：:]\s*(.+)", 整本)
    if not m:
        问.append("没写「落点」")
    else:
        抽 = ("明白了", "懂了", "释然", "放下了", "感悟", "领悟", "成长", "救赎")
        中 = [w for w in 抽 if w in m.group(1)]
        if 中:
            问.append("落点写成了看不见的东西（%s）—— 落点必须是最后一镜画面里能看见的"
                      % "、".join(中))

    return {"过": not 问, "问题": 问, "数字": n}


