"""
影匠 · 编剧
================================================================
四步写剧本 —— 2026-10-15 立。

为什么拆成四步：

用户 2026-10-15 的原话：「我试着生成了，但**剧本根本就没什么内容**」。
我原来是一次调模型，一口气要它吐出「一句话故事 + 人物 + 分场 + 台词」四样东西。
结果就是**每一样都写了，每一样都不够**：人物只有一句「老王，60 岁，修鞋匠」，
分场只有「谁在场 / 发生了什么」，台词一句都没有。

四步法不是把一件事拆慢，是**把判断权切成小块交给他**：

    第 1 步  梗概     —— 3 行，他 30 秒能看完，说「这个方向行 / 不行」
    第 2 步  人物     —— 2–4 个人，每人一个「一眼能认出来的东西」
    第 3 步  分场     —— 5–9 场，每场一个变化
    第 4 步  台词     —— 全片台词，每句 ≤18 字

前一步没过，后一步**不许开** —— 因为故事不行的时候，往下写多少都是白写
（我犯过 4 次这个错：他说故事不行，我回去修字幕、换种子）。

用法:
    import 编剧
    r = 编剧.第一步_梗概("一个修鞋匠和一个不肯走的小女孩")
    print(r["文"])
    r2 = 编剧.第二步_人物(r["文"])
    ...
    print(编剧.自检(整本))
"""

