"""提示词写法对照试验：同一格、同一个种子，只换提示词的写法，看图差多少。

## 为什么要这个

用户 2026-10-14 看完四部片子之后连着两天追问同一件事：

> 你的这些提示词用这么多生硬的，或者是说带有文学性色彩的描写干什么？
> 作为视频生成的提示词，你应该是简单直接明了的将你所想表达的文学氛围感，
> 用简单直白的构图的方式将它描述出来，而不是故弄玄虚的，像写小说、写文章一样。
> **你懂视频生成和写小说之间的区别吗？**

他随手引的是《觉醒》格6 的光色字段：

> 冷灰天光从右上方来，把他的后脑照出一层灰白边；
> 那页纸是唯一的浅色发光面，很灰、很薄，**像泡过水的旧文书**。

## 小说和视频提示词的区别（这个脚本就是拿来验这一条的）

| | 写小说 | 写视频提示词 |
|---|---|---|
| 读者 | 人的想象力 | 模型只画**被点名的东西** |
| 比喻 | 「像泡过水的旧文书」→ 读者自己联想 | **要么被忽略，要么被照字面画出来**（真画一张泡水的文书） |
| 最高级 | 「唯一」「最」很有力 | 模型不解析「唯一」，只当噪声 |
| 长度 | 越长越细 | **越长越糊** —— 第 5 个从句不细化第 1 个，它跟第 1 个抢注意力 |
| 该写什么 | 氛围、心境、留白 | **主体 + 动作 + 景别 + 位置 + 光的方向冷暖** |

本项目实测：`磨刀` 45 格平均 237 字，`觉醒` 74 格平均 278 字，最长 402 字。
业界能给模型稳定接住的经验值是 **40–80 字**。**超了 3–7 倍。**

## 用法

    python _试提示词写法.py 觉醒 --格 6
    python _试提示词写法.py 觉醒 --格 6 --写法 C     # 只跑某一种
"""
