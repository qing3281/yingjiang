def 抠原词(戏, 号):
    """返回 (景别, 提示词原文, 尾串)。

    ★ 分开返回是为了让所有写法**吃同一份景别前缀**。第一版把 B/C 写成
      「过肩镜头」「过肩中近景」（中文），A 却是 `medium close-up`（英文），
      结果 B/C 被削了腿 —— 这个模型认英文景别，中文的基本不当回事。
      **对照实验里，两边必须拿到一模一样的框。**
    """
    import io
    import re
    文 = io.open(os.path.join(根, "作品", 戏, "02-九宫格.md"), encoding="utf-8").read()
    m = re.search(r"^##\s*格\s*%d\s*(.*?)(?=^##\s*格\s*|\Z)" % 号, 文, flags=re.M | re.S)
    if not m:
        raise SystemExit("  ✗ 02-九宫格.md 里没有 格%d" % 号)
    体 = m.group(1)

    def 取(键):
        mm = re.search(r"^\-\s*\*\*%s\*\*\s*[:：]\s*(.*)$" % 键, 体, flags=re.M)
        return mm.group(1).strip() if mm else ""

    景 = 取("景别") or "medium shot"
    光 = 取("光色")
    尾 = "，".join(x for x in (光, "电影写实，胶片颗粒，硬光长阴影") if x)
    return 景, 取("提示词"), 尾


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("戏")
    ap.add_argument("--格", type=int, default=6)
    ap.add_argument("--写法", default="ABC", help="要跑哪几种，默认 ABC")
    ap.add_argument("--端点", default="本机", choices=["本机", "远端"])
    ap.add_argument("--出到", default="")
    参 = ap.parse_args()

    出 = 参.出到 or os.path.join(根, "作品", 参.戏, "_试提示词写法")
    os.makedirs(出, exist_ok=True)

    点 = 引擎.换端点(参.端点)
    在 = 引擎.在线()
    print("=" * 72)
    print("  《%s》 格%d —— 提示词写法对照（同一个种子 %d）" % (参.戏, 参.格, 种子))
    print("  端点 %s　在线=%s　%s　显存空闲 %s GB" % (
        参.端点, 在.get("在线"), 在.get("显卡", ""), 在.get("显存空闲GB")))
    print("=" * 72)

    景, 原词, 尾 = 抠原词(参.戏, 参.格)

    果 = []
    for 键 in 参.写法:
        if 键 not in 写法表:
            continue
        名, 身 = 写法表[键]
        体 = 原词 if 身 is None else 身
        # ★ 所有写法吃同一份框：英文景别 + 正文 + 同一串尾
        词 = " ".join(f"{景}。{体}，{尾}".split())
        print("\n  ── %s · %s" % (键, 名))
        print("     %d 字：%s" % (len(词), 词[:300]))

        t = time.time()
        r = 导演.开镜(词, 风格="cinematic-real", 角色=[], 种子=种子,
                      宽=宽, 高=高, 文件名="试词_%s_格%d" % (键, 参.格),
                      用定妆照=False)
        路 = r.get("路", "")
        print("     ✓ %.1f 秒  %s" % (time.time() - t, os.path.basename(路)))
        果.append((键, 名, len(词), 路))

    # 拼图：把写法标签和字数**烧进像素里**（吃过一次「靠数行数对错文件」的亏）
    print("\n  ── 拼对照图")
    from PIL import Image, ImageDraw
    图s = [Image.open(p).convert("RGB") for _, _, _, p in 果]
    W = 900
    H = int(图s[0].height * W / 图s[0].width)
    图s = [im.resize((W, H), Image.LANCZOS) for im in 图s]
    版 = Image.new("RGB", (W, (H + 34) * len(图s)), (12, 12, 12))
    笔 = ImageDraw.Draw(版)
    for i, im in enumerate(图s):
        y = i * (H + 34)
        版.paste(im, (0, y))
        笔.text((8, y + H + 8), "%s · %s" % (果[i][0], 果[i][1]), fill=(255, 220, 80))
    出图 = os.path.join(根, "作品", 参.戏, "_试提示词写法_格%d.png" % 参.格)
    版.save(出图)
    print("  ✓ %s  %d×%d  （从上到下 %s）" % (
        出图, 版.width, 版.height, " / ".join(f"{k} {n}字" for k, _, n, _ in 果)))
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
