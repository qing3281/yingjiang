# -*- coding: utf-8 -*-
"""
影匠 · 导演  —— 把「风格 + 角色 + 情节」拧成一条指令
================================================================
这是你日常真正会用的那一层。下面三行就是一个镜头：

    import 导演
    导演.立戏("凌霜单骑闯关")
    导演.定角("凌霜", 性别="女", 发="银白长发披肩", 眼="紫色杏眼",
              服="黑色修身长袍，银色云纹刺绣", 特征="左眼下有一颗小痣")
    镜 = 导演.开镜("凌霜走在雪原上，回头看向镜头", 风格="cinematic-real")

它做的事：
    风格库.编译(风格)  +  角色库.外貌串(角色)  +  你的情节描述
        ↓
    一整条英文提示词 + 角色固定的种子
        ↓
    引擎.文生图 / 引擎.图生视频
"""

import os
import time

import 引擎
import 风格库
import 角色库

这里 = os.path.dirname(os.path.abspath(__file__))
作品 = os.path.join(这里, "作品")
os.makedirs(作品, exist_ok=True)

_当前戏 = {"名": "", "风格": "cinematic-real", "角色": []}


# ============================================================
# 立戏 / 定角
# ============================================================

def 立戏(戏名, 默认风格="cinematic-real", 默认角色=None):
    """开一部戏。之后的镜头默认用这部戏的风格和角色。"""
    _当前戏["名"] = 戏名
    _当前戏["风格"] = 默认风格
    _当前戏["角色"] = list(默认角色 or [])
    d = os.path.join(作品, _安全名(戏名))
    os.makedirs(d, exist_ok=True)
    print(f"▶ 立戏《{戏名}》  默认风格 {风格库.取(默认风格)['中文']}  目录 {d}")
    return d


def 定角(名, **字段):
    """登记一个角色（转发给角色库）。"""
    r = 角色库.建(名, **字段)
    if 名 not in _当前戏["角色"]:
        _当前戏["角色"].append(名)
    a = 角色库.外貌串(名)
    print(f"▶ 定角【{名}】  种子 {a['种子']}")
    print(f"    {a['串']}")
    return r


def 戏目录():
    名 = _当前戏["名"] or "未命名"
    d = os.path.join(作品, _安全名(名))
    os.makedirs(d, exist_ok=True)
    return d


def _安全名(s):
    for c in '\\/:*?"<>|':
        s = s.replace(c, "_")
    return s.strip() or "未命名"


# ============================================================
# ★ 开镜 —— 核心
# ============================================================

def 开镜(
    情节,
    风格=None,
    角色=None,
    景别="",
    镜头="",
    种子=None,
    宽=1024,
    高=1024,
    步数=None,
    文件名="",
    报=None,
):
    """
    出一个镜头（首帧图）。

    参数：
      情节   这一镜发生什么（中文，随便写）
      风格   风格键；不给就用这部戏的默认
      角色   角色名或名字列表；不给就用这部戏登记的全部
      景别   覆盖景别，例如 "wide shot" / "close-up"
      镜头   覆盖镜头句
      种子   不给就自动：**有主角就锁主角的种子**（保证同一张脸）
      文件名 自定义输出名
    """
    报 = 报 or (lambda s: print("   ", s))
    风 = 风格 or _当前戏["风格"]
    角 = 角色 if 角色 is not None else _当前戏["角色"]
    if isinstance(角, str):
        角 = [角]

    # --- 拼角色串 ---
    角色串 = ""
    if 角:
        角色串 = 角色库.多人串(角)

    # --- 拼镜头 ---
    镜 = 镜头
    if 景别:
        镜 = f"{景别}, " + (镜 or "")
    if not 镜:
        镜 = None

    # --- 编译提示词 ---
    s = 风格库.取(风)
    r = 风格库.编译(风, 额外=情节, 角色=角色串, 镜头=镜)

    # --- 种子：锁主角 ---
    if 种子 is None:
        if 角:
            种子 = 角色库.外貌串(角[0])["种子"]
        else:
            import random
            种子 = random.randint(1, 2**31)

    n = 文件名 or f"{_当前戏['名'] or '镜'}_{int(time.time())}"
    存 = os.path.join(戏目录(), n + ".png")

    报(f"风格【{s['中文']}】 种子 {种子}" + (f" 角色 {'+'.join(角)}" if 角 else ""))
    果 = 引擎.文生图(
        r["正向"],
        负面=r["负向"],
        种子=种子,
        宽=宽,
        高=高,
        步数=步数 or 8,
        前缀=f"影匠/{_当前戏['名'] or '镜'}",
        报=报,
        存到=存,
    )
    果["风格"] = s["中文"]
    果["角色"] = 角
    果["正向"] = r["正向"]
    return 果


def 连镜(情节, **kw):
    """同样的参数再开一镜，只是换情节 —— 保持风格和角色一致。"""
    return 开镜(情节, **kw)


# ============================================================
# 动起来
# ============================================================

def 让镜动(镜头果, 动作描述, 模板="wan22_i2v", 帧数=49, 帧宽=832, 帧高=480, 报=None):
    """
    把一镜的图变成一段视频。动作描述写「怎么动」，不写「是什么」。

    落盘位置：优先跟**图片自己所在的目录**走 —— 这样即使没先 立戏，
    也不会掉进「未命名」。图片不在作品目录下时才退回当前戏目录。
    """
    报 = 报 or (lambda s: print("   ", s))
    图路 = 镜头果["路"] if isinstance(镜头果, dict) else str(镜头果)
    图目录 = os.path.dirname(os.path.abspath(图路))
    作品根 = os.path.abspath(作品)
    落 = 图目录 if 图目录.startswith(作品根) else 戏目录()

    r = 引擎.图生视频(
        图路,
        动作描述,
        种子=镜头果.get("种子") if isinstance(镜头果, dict) else None,
        帧数=帧数,
        帧率=16,
        宽=帧宽,
        高=帧高,
        模板=模板,
        前缀=f"影匠/{os.path.basename(落)}",
        报=报,
        存到=os.path.join(落, os.path.basename(图路).rsplit(".", 1)[0] + ".mp4"),
    )
    return r


# ============================================================
# 看
# ============================================================

def 看风格(关键词=""):
    风格库.打印全部() if not 关键词 else None
    if 关键词:
        for k, 中, 用 in 风格库.找(关键词):
            print(f"  {k:<18} {中:<10} {用}")


def 看角色():
    角色库.打印()


if __name__ == "__main__":
    import sys

    if len(sys.argv) >= 2 and sys.argv[1] == "风格":
        看风格(sys.argv[2] if len(sys.argv) > 2 else "")
    elif len(sys.argv) >= 2 and sys.argv[1] == "角色":
        看角色()
    else:
        print(__doc__)
        print("命令：python 导演.py 风格 [关键词] | python 导演.py 角色")
