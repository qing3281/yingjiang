# ─────────────────────────────── 剧本解析 ───────────────────────────────

def 读剧本(路: str) -> list[dict]:
    """切出 35 个镜头，每个是一个 dict。"""
    with open(路, encoding="utf-8") as f:
        文 = f.read()
    块s = re.split(r"^### 镜\s*(\d+)", 文, flags=re.M)[1:]
    镜们 = []
    for i in range(0, len(块s), 2):
        号 = int(块s[i])
        体 = 块s[i + 1]
        名 = 体.split("\n", 1)[0].strip("　 \t")
        镜 = {"号": 号, "名": 名}
        for 段 in re.findall(r"^- \*\*(.+?)\*\*：(.+)$", 体, flags=re.M):
            镜[段[0].strip()] = 段[1].strip()
        镜们.append(镜)
    return 镜们


def 挑角色(镜: dict) -> list[str]:
    原 = " ".join(str(镜.get(k, "")) for k in ("人物", "动作", "台词", "布景", "名"))
    有 = []
    for k in 角色表:
        if k in 原:
            有.append(k)
    # 「明教众人」写成「明教」也算
    if "明教" in 原 and "明教众人" not in 有:
        有.append("明教众人")
    return 有


def 提台词(原: str) -> str:
    if not 原:
        return ""
    句 = re.findall(r"[「『\"]([^」』\"]+)[」』\"]", 原)
    if 句:
        return " ".join(s.strip() for s in 句 if s.strip())
    s = re.sub(r"\*\*", "", 原)
    s = re.sub(r"（[^）]*）|\([^)]*\)", "", s)
    s = s.strip(" 。，、:：")
    if s.strip(" 。，、:：（）()…—–-") in ("无", "無", "none", "None", "N/A"):
        return ""
    return s


