def 查纯英文(动作: str, 镜号: int) -> None:
    """★ 硬保险：提示词里只要有可发音的非 ASCII 字符就拒绝跑。

    来历：《不烧心》第一版全片声音报废，就是因为提示词里混了中文舞台提示，
    MiniMax 的语音模型照着念了出来。这个检查必须挡在调用之前。
    """
    坏 = []
    for ch in 动作:
        o = ord(ch)
        if o < 128:
            continue
        # 弯引号、破折号之类只是标点，念不出来，放过
        if 0x2018 <= o <= 0x201F or o in (0x2013, 0x2014, 0x2026):
            continue
        坏.append(ch)
    if 坏:
        样 = "".join(dict.fromkeys(坏))[:20]
        raise SystemExit(
            f"\n❌ 镜 {镜号:02d} 的动态提示词里有 {len(坏)} 个可发音的非 ASCII 字符：\n"
            f"   「{样}」\n"
            f"   这会被人声模型念出来（《不烧心》翻过的车）。\n"
            f"   请把 光明顶词表.py 里这一条改成纯英文再跑。\n"
        )


def 出动态(镜: dict, 种子: int) -> str | None:
    from MiniMax动态 import 出动态 as 跑

    from 光明顶词表 import 取动态词

    首 = os.path.join(首帧根, f"{镜['号']:02d}_首帧.png")
    出 = os.path.join(镜根, f"{镜['号']:02d}_动态.mp4")
    if not os.path.isfile(首):
        print("  ❌ 缺首帧，先跑 --出首帧")
        return None
    动作 = 取动态词(镜["号"])
    if not 动作:
        print(f"  ❌ 词表里没有镜 {镜['号']:02d}")
        return None
    查纯英文(动作, 镜["号"])
    print(f"  提示词 {len(动作)} 字符，纯英文 ✓")
    return 跑(首, 动作, "", 出, 种子=种子 + 镜["号"] * 137,
              主体=造主体(镜), 场景锚=场景锚)


# ─────────────────────────────── main ───────────────────────────────

def main() -> int:
    ap = argparse.ArgumentParser(description="《光明顶》35 镜总调度")
    ap.add_argument("--出首帧", action="store_true")
    ap.add_argument("--出动态", action="store_true")
    ap.add_argument("--只", nargs="*", type=int, default=[])
    ap.add_argument("--种子", type=int, default=7001)
    ap.add_argument("--列", action="store_true")
    a = ap.parse_args()

    os.makedirs(首帧根, exist_ok=True)
    os.makedirs(镜根, exist_ok=True)

    镜们 = 读剧本(剧本路)
    if a.只:
        镜们 = [m for m in 镜们 if m["号"] in a.只]
    print(f"从 {剧本路} 解析出 {len(镜们)} 个镜头")

    if a.列:
        for m in 镜们:
            print(f"  {m['号']:02d}  {m['名']}  [{景别.get(m['号'],'中景')}]  "
                  f"角色={'+'.join(挑角色(m)) or '无'}")
        return 0

    if not (a.出首帧 or a.出动态):
        ap.print_help()
        return 0

    好 = 坏 = 0
    for m in 镜们:
        print(f"\n[{m['号']:02d}/{len(镜们)}] 镜 {m['号']:02d}  {m['名']}")
        r = 出首帧(m, a.种子) if a.出首帧 else 出动态(m, a.种子)
        if r:
            好 += 1
        else:
            坏 += 1

    阶段 = "首帧" if a.出首帧 else "动态"
    print(f"\n{'✅' if 坏 == 0 else '⚠️'} {阶段} {好}/{len(镜们)} 条"
          + (f"，失败 {坏} 条" if 坏 else ""))
    return 0 if 坏 == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
