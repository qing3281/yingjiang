def 查角色齐全(镜: dict) -> None:
    """★ 硬保险：剧本点名的人，提示词里必须都有设计。

    来历：镜 09（崆峒宗维侠起手）当时角色表里没有宗维侠，模型被要求画两个人
    却只有一份人物设定，就**把张无忌复制了一份当对手**（两个一模一样的白衣
    少年对打）。镜 11/12/14/15/17 同理。

    做法：把「人物」字段里 + 分隔的名字逐个对照角色表，对不上就报错。
    门派名（崆峒/华山/昆仑…）不算人名，允许缺失。
    """
    人物 = str(镜.get("人物", ""))
    点名 = [s.strip() for s in re.split(r"[+＋、,，/]", 人物) if s.strip()]
    门派词 = ("崆峒", "华山", "昆仑", "少林", "武当", "峨嵋", "峨眉", "明教", "六派", "群像")
    缺 = []
    for 名 in 点名:
        净 = re.sub(r"（[^）]*）|\([^)]*\)", "", 名).strip()
        if not 净 or 净 in ("无", "無"):
            continue
        if any(净 in k or k in 净 for k in 角色表):
            continue
        if any(w in 净 for w in 门派词) and len(净) <= 6:
            continue                      # 「崆峒五老」这类背景群像，放过
        缺.append(净)
    if 缺:
        raise SystemExit(
            f"\n❌ 镜 {镜['号']:02d}「{镜.get('名','')}」点名了没有设计的人物：{缺}\n"
            f"   不补设计的话，模型会把已有角色复制一份来当对手\n"
            f"   （镜 09 就出过两个张无忌对打）。请加到 角色表。\n"
        )


