def 自检() -> int:
    """检查音效表：名字在库里、打点不超镜长、音量在 0~1。返回问题条数。"""
    import 音效

    镜长 = 124 / 24.0  # 5.1667 秒
    问题 = 0
    for 号, 点们 in sorted(音效表.items()):
        for i, (秒, 名, 量) in enumerate(点们):
            if 名 not in 音效.库:
                问题 += 1
                print(f"  ❌ 镜{号:02d} 第{i}击：库里没有「{名}」")
            if 秒 < 0 or 秒 >= 镜长:
                问题 += 1
                print(f"  ❌ 镜{号:02d} 第{i}击：{秒}s 超出镜长 {镜长:.4f}s")
            if not (0 < 量 <= 1):
                问题 += 1
                print(f"  ❌ 镜{号:02d} 第{i}击：音量 {量} 不在 0~1")
    for 号, 量 in 雨量:
        if not (0 < 量 <= 2):
            问题 += 1
            print(f"  ❌ 镜{号:02d} 雨量 {量} 不合理")
    if sorted(音效表) != [x for x, _ in sorted(雨量)]:
        问题 += 1
        print("  ❌ 音效表与雨量的镜号对不上")
    总击 = sum(len(v) for v in 音效表.values())
    print(f"  镜 {len(音效表)} 个，共 {总击} 击；{'全部通过 ✅' if 问题 == 0 else f'{问题} 处问题'}")
    return 问题


if __name__ == "__main__":
    raise SystemExit(自检())
