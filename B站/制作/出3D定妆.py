def 出(键: str, 种子: int, 宽=1152, 高=1536, 快=False) -> str | None:
    c = 角色表[键]

    # 走**纯文本出图**，不喂参考图
    #
    # 原因：Qwen-Image-Edit 有个治不好的毛病 —— 它会把「参考图」和「生成结果」
    # 并排画在同一张画布上，中间那格是原图翻版，结果是画面被切成几条还互相叠着。
    # 但角色设计锁现在写得足够细（发色渐变/耳朵位置/围裙图案/尾巴形状逐条列死），
    # 纯文本就能画出正确的设计，且完全没有拼贴。
    #
    # 副作用（好的）：从零画出来的形象比「翻译 2D 原图」更贴设计，
    # 也不会在 3D 化时被压暗 —— 用户 m03329 提的两个问题一起解决。
    词 = (
        f"【任务】一张 3D 卡通渲染的**标准角色定妆图**：角色站在画面正中，"
        f"正面朝向镜头，全身从头到脚都在画面里，四周留出空白。"
        f"背景是{ c['底色'] }的**纯净单色背景**，不要任何场景、不要地面、不要投影、"
        f"不要文字、不要分格、不要边框，画面里只有这一个角色。\n\n"
        f"【角色设计 —— 逐条照做】{c['词']}\n\n"
        f"{画风锁}"
    )
    负 = ("多个角色, 两个角色, 分格, 拼图, 三视图, 设定表, 文字, 水印, 签名, 边框, "
          "写实, 照片, 真人, 阴暗, 暗沉, 低饱和, 场景, 背景环境, "
          "男孩, 男性, 男人, 胡子, 方下巴, 粗脖子, 男性骨架, 短发男")

    os.makedirs(出根, exist_ok=True)
    print(f"\n=== {c['名']}（种子 {种子}）===")
    r = 纯文本跑(词, 种子=种子, 宽=宽, 高=高, 负面=负)
    if not r:
        return None
    im = Image.open(r).convert("RGB")
    p = os.path.join(出根, f"{c['名']}.png")
    im.save(p)
    print(f"✓ {p}  {im.size}")
    return p


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--角色", nargs="*", default=[], help="键名，缺省=全部")
    ap.add_argument("--种子", type=int, default=3001)
    ap.add_argument("--快", action="store_true")
    a = ap.parse_args()

    键们 = a.角色 or list(角色表)
    for i, k in enumerate(键们):
        if k not in 角色表:
            print(f"✗ 没有这个角色：{k}")
            continue
        出(k, a.种子 + i * 13, 快=a.快)

    # 拼一张总览
    fs = []
    for k in 角色表:
        p = os.path.join(出根, f"{角色表[k]['名']}.png")
        if os.path.isfile(p):
            fs.append((角色表[k]["名"], p))
    if fs:
        字 = None
        from PIL import ImageDraw, ImageFont

        字 = ImageFont.truetype(r"C:\Windows\Fonts\msyhbd.ttc", 26)
        H = 620
        块 = [(n, Image.open(p).convert("RGB")) for n, p in fs]
        块 = [(n, i.resize((int(i.width * H / i.height), H), Image.LANCZOS)) for n, i in 块]
        W = sum(i.width for _, i in 块) + 16 * (len(块) - 1)
        sh = Image.new("RGB", (W, H + 40), (16, 16, 20))
        d = ImageDraw.Draw(sh)
        x = 0
        for n, i in 块:
            sh.paste(i, (x, 40))
            d.text((x + 8, 8), n, font=字, fill=(255, 205, 90))
            x += i.width + 16
        o = r"D:\DSHworkspace\_3D定妆总览.png"
        sh.save(o)
        print(f"\n✅ 总览 → {o}  {sh.size}")
    return 0


