"""《龙族 · 雨夜》音效打点表。

所有音效都由 音效.py 程序合成，没有一个来自素材库 —— 好处是**每一击都能精确
对齐到帧**，不受采样长度和起振延迟的影响。

时长：MiniMax 每条固定 124 帧 @24fps = **5.1667 秒**（`MiniMax动态.py:48 帧每镜`）。
所以下面的打点秒数最大只能到 5.16，超出的会被 合成龙族.py 丢弃并告警。

设计原则
--------
1. **雨铺满全片**，但每一镜的雨量不同：车内 0.45（闷）、车外 1.0（正常）、
   撞进白光和最后突围 1.25~1.6（豪雨）。雨量写在 `雨量` 里。
2. **每一击都要有声**。参照《光明顶》的教训：没有打点的动作镜头，
   观众会觉得「轻飘飘」。
3. **同一个音效在同一镜内多次出现**时，合成器会自动换种子（`镜号*101 + k*17 + 1`），
   所以不会听出是同一个采样。
4. 音量是**相对值**，合成器还会按镜压峰（上限 0.85），所以这里不用怕给大。

音效清单（音效.py）
------------------
雨 雷 引擎 金属 气爆 马啸 神之声 刀锋 星光突刺 心跳
（另有《光明顶》那批武打音：风 啸 掌 兵器 鸣 炸 碎 衣 蓄 踏 钟）

★★ 音量怎么定 —— 这条是踩过坑才明白的
--------------------------------------
**「音量」不等于「对响度的贡献」。** 每个音效的固有 RMS 差得很远：
`引擎` 0.3050（4 秒持续音，全库最响）、`神之声` 0.1226（3 秒）、
`金属` 0.1273（0.9 秒）、`刀锋` 0.0948（0.75 秒瞬态）、`雷` 0.0676（4.5 秒）。

第一版没考虑这件事，结果**开场给了三处引擎（0.34/0.52/0.86），全片最响的反而是
前 20 秒**，中间 45 秒掉到 0.03~0.09，镜 13 的高潮只有 0.09 —— 完全反了。

所以现在按「**持续音铺底、瞬态音打点**」排：
- 需要**撑住一段时间的响度** → 用 `引擎` / `神之声` / `雷`（长音，RMS 贡献大）
- 需要**打一个点** → 用 `刀锋` / `金属` / `星光突刺` / `心跳`（瞬态，给多大都只是一下）
- 开场（镜 01~04）的音量**刻意压低**，把响度让给镜 09~14
"""

