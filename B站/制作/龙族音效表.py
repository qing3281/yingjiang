def 自检() -> int:
    """跑之前先自检：别名对不对、打点有没有超出镜长。"""
    from 音效 import 库

    镜长 = 124 / 24.0            # 5.1667 秒
    坏 = 0
    for 号 in sorted(音效表):
        for t, 名, 音 in 音效表[号]:
            if 名 not in 库:
                印 = f"  ❌ 镜 {号:02d} 音效库里没有「{名}」"
                坏 += 1
            elif t >= 镜长:
                印 = f"  ❌ 镜 {号:02d} 打点 {t}s 超出镜长 {镜长:.2f}s"
                坏 += 1
            elif not (0.0 < 音 <= 1.0):
                印 = f"  ⚠ 镜 {号:02d}「{名}」音量 {音} 不在 0~1.0"
            else:
                continue
            print(印)
    总 = sum(len(v) for v in 音效表.values())
    print(f"  {len(音效表)} 镜 / {总} 击 / 雨量行 {len(雨量)}")
    if 坏:
        print(f"❌ 自检不过：{坏} 处")
        return 1
    print("✅ 自检通过")
    return 0


if __name__ == "__main__":
    raise SystemExit(自检())
