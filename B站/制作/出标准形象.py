def 转成可喂的(路: str) -> str:
    """Qwen 工作流只认 png/jpg，webp 先转一份 png 放旁边。"""
    if not 路.lower().endswith(".webp"):
        return 路
    png = 路[:-5] + "_转.png"
    if os.path.isfile(png):
        return png
    from PIL import Image

    Image.open(路).convert("RGB").save(png)
    return png


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--只出", type=int, default=0, help="只出第 N 个（1 起）")
    ap.add_argument("--宽", type=int, default=3072)
    ap.add_argument("--高", type=int, default=1728)
    a = ap.parse_args()

    os.makedirs(出根, exist_ok=True)
    表 = 角色表
    if a.只出:
        表 = [角色表[a.只出 - 1]]

    总 = time.time()
    for i, c in enumerate(表, 1):
        参 = 转成可喂的(c["参考"])
        if not os.path.isfile(参):
            print(f"❌ 缺参考图 {参}")
            return 1
        词 = (
            f"角色设定卡。角色是：{c['设定']}"
            f"{画风锁}{版式}"
            "画面里不要出现任何文字、不要水印、不要签名。"
        )
        print(f"\n[{i}/{len(表)}] {c['名']}")
        t = time.time()
        r = 跑([参], 词, 种子=5000 + i * 17, 宽=a.宽, 高=a.高, 拆联=False)
        if not r:
            print("   ❌ 生成失败")
            continue
        from PIL import Image

        im = Image.open(r)
        到 = os.path.join(出根, c["名"] + ".png")
        im.save(到)
        print(f"   ✓ {time.time()-t:.0f} 秒  {im.size}  →  {到}")

    print(f"\n✅ 全部 {len(表)} 张，共 {time.time()-总:.0f} 秒 → {出根}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
