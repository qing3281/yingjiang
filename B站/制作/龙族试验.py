def 跑(a) -> int:
    import 出图_纯文本 as 图

    os.makedirs(试验根, exist_ok=True)
    if a.重出:
        for k in 试验:
            p = os.path.join(试验根, f"{k}.png")
            if os.path.isfile(p):
                os.remove(p)
                print(f"  删掉 {p}")

    清单 = [(k, v) for k, v in 试验.items() if not os.path.isfile(os.path.join(试验根, f"{k}.png"))]
    if not 清单:
        print("四张都已有。加 --重出 可重跑。")
        return 0

    print(f"要出 {len(清单)} 张，每张 40 步 / CFG 4.0（高质量档）\n")
    t0 = time.time()
    for i, (名, 词) in enumerate(清单, 1):
        print(f"[{i}/{len(清单)}] {名}   提示词 {len(词)} 字符")
        t1 = time.time()
        r = 图.跑(词, 种子=7300 + i * 137, 宽=宽, 高=高, 负面=负面, 静默=True)
        if not r:
            print("   ✗ 失败")
            continue
        from PIL import Image

        p = os.path.join(试验根, f"{名}.png")
        Image.open(r).convert("RGB").save(p)
        print(f"   ✓ {time.time()-t1:.0f} 秒 → {p}")

    print(f"\n✅ 全部用时 {time.time()-t0:.0f} 秒")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--重出", action="store_true")
    return 跑(ap.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
