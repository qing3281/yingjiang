def 归一(s):
    """去掉标点和技术词，只留「讲了什么」"""
    s = (s or "").lower()
    s = 技术词正则.sub(" ", s)
    s = 标点正则.sub("", s)
    return s


def 相似(a, b):
    """
    字符 2-gram 的 Jaccard。比 SequenceMatcher 稳：
    同一个词换个位置，SM 会掉一大截，2-gram 不会。
    """
    a, b = 归一(a), 归一(b)
    if not a and not b:
        return 1.0
    if not a or not b:
        return 0.0
    if a == b:
        return 1.0
    A = {a[i:i + 2] for i in range(len(a) - 1)} or {a}
    B = {b[i:i + 2] for i in range(len(b) - 1)} or {b}
    return len(A & B) / len(A | B)


def 关键词(串):
    """
    外貌串 -> 关键词。

    剧组/导演.md 的判据：把角色卡那行的英文外貌串按逗号切开，
    取每个片段的首词（silver-white / violet / fair …）。
    中文片段取前 6 字（中文没法这么切，保守点）。
    去重，保序。短词（the / and 之类）不算关键词。
    """
    出, 见过 = [], set()
    段们 = []
    for 行 in re.split(r"[\n。；;]", 串 or ""):
        行 = 行.strip()
        if not 行:
            continue
        # 「凌霜：long silver-white hair, …」—— 冒号前是角色名，不是外貌词
        行 = re.sub(r"^[^：:]{0,14}[：:]\s*", "", 行)
        段们 += 标点正则.split(行)
    for 段 in 段们:
        段 = (段 or "").strip()
        if not 段:
            continue
        if re.match(r"^[a-z]", 段, re.I):
            词 = 段.split()[0].lower()
        else:
            词 = 段[:6]
        if len(词) < 3 or 词 in 见过:
            continue
        见过.add(词)
        出.append(词)
    return 出


def 命中数(文本, 词表):
    低 = (文本 or "").lower()
    return [k for k in 词表 if k in 低]


def 查表(文本, 词表, 中英=None):
    """
    按词表查「出现了哪几种」。
    英文按词边界算，中文直接找子串 —— 免得 company 里的 pan 被算成摇镜。
    中英：{中文说法: 英文词表项}。模板里镜头运动是写在「动作」正文里的中文
    （「摄影机固定不动」「摄影机缓缓推近」），要认出来得靠这张别名表；
    同一个运动的中英两种写法算一种。
    """
    低 = (文本 or "").lower()
    出 = []
    for w in 词表:
        w低 = w.lower()
        if re.search(r"[a-z]", w低):
            if re.search(r"(?<![a-z])" + re.escape(w低) + r"(?![a-z])", 低):
                出.append(w)
        elif w in (文本 or ""):
            出.append(w)
    if 中英:
        for 中文, 英文 in 中英.items():
            if 中文 in (文本 or ""):
                出.append(英文)
    # 去重（保序）：中英两种写法指的是同一个运动，别算成两种
    见过, 净 = set(), []
    for x in 出:
        x低 = x.lower()
        if x低 in 见过:
            continue
        见过.add(x低)
        净.append(x)
    return 净


def 景别(文本):
    """从一串文本里认出景别（取最长匹配，免得 wide shot 被 medium shot 抢）"""
    低 = (文本 or "").lower()
    for k in sorted(景别表, key=len, reverse=True):
        if re.search(r"(?<![a-z-])" + re.escape(k) + r"(?![a-z-])", 低):
            return k
    return ""


def 强度值(文本):
    m = re.search(r"(\d+(?:\.\d+)?)", 文本 or "")
    return float(m.group(1)) if m else None


