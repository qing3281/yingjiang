class 解析器:
    """
    解析产物 markdown。**解析失败不静默** —— 记行号 + 原始行，
    宁可报「我没看懂」也不猜。猜出来的绿勾比不报还危险。
    """

    def __init__(self, 路径):
        self.路径 = 路径
        self.名 = os.path.basename(路径)
        self.行 = []
        self.报 = []          # 解析失败：[行号, 原文]
        try:
            with open(路径, "r", encoding="utf-8") as f:
                self.行 = f.read().splitlines()
        except Exception as e:
            self.报.append(("读不到文件", f"{路径}：{e}"))
        self.根 = os.path.splitext(self.名)[0]

    # ---------- 基础 ----------

    def _行号(self, i, 标题):
        return f"{self.名}:{i + 1} 「{标题}」"

    def 段落(self, 标题词):
        """取 `## 角色卡` 这类段落的内容（直到下一个同级或更高级标题）"""
        for i, s in enumerate(self.行):
            if re.match(r"^#{1,6}\s*" + re.escape(标题词) + r"\s*$", s.strip()):
                级 = len(s.strip()) - len(s.strip().lstrip("#"))
                取 = []
                for j in range(i + 1, len(self.行)):
                    t = self.行[j]
                    if 重任意标题.match(t):
                        这级 = len(t) - len(t.lstrip("#"))
                        if 这级 <= 级:
                            break
                    取.append(t)
                return 取
        return []

    def 有段落(self, 标题词):
        for s in self.行:
            if re.match(r"^#{1,6}\s*" + re.escape(标题词) + r"\s*$", s.strip()):
                return True
        return False

    def 表(self, 必须是=()):
        """
        收一个 markdown 表：返回 [(行号, 值)] + 表头。
        表头从第一个表格块取；表头列数和数据列数不一致就记解析失败。

        必须是：给几个列名（子串匹配，忽略空格），只收含其中之一的那张表。
        01-节拍拆解.md 里「节拍表」排在「锚点表」前面，不指定就会收到节拍表，
        于是「拐点类型」列找不到、行数也数成了节拍数 —— 全是误报。
        一张都没命中时退回第一张表，让调用方用自己的话把真实表头报出来。
        """
        候选 = []
        i = 0
        while i < len(self.行):
            if 重表格行.match(self.行[i]):
                块 = []
                j = i
                while j < len(self.行) and 重表格行.match(self.行[j]):
                    块.append((j, self.行[j]))
                    j += 1
                i = j
                数据 = [(n, s) for n, s in 块 if not 重分隔行.match(s)]
                if not 数据:
                    continue
                表头 = [c.strip() for c in 数据[0][1].strip().strip("|").split("|")]
                出 = []
                for n, s in 数据[1:]:
                    列 = [c.strip() for c in s.strip().strip("|").split("|")]
                    if len(列) != len(表头):
                        self.报.append((self._行号(n, "表格"), f"列数 {len(列)} ≠ 表头 {len(表头)}：{s.strip()}"))
                        continue
                    出.append((n, dict(zip(表头, 列))))
                if not 出:
                    continue
                if not 必须是:
                    return 出, 表头
                纯 = [h.replace(" ", "") for h in 表头]
                命中 = any(别.replace(" ", "") in h for 别 in 必须是 for h in 纯)
                if 命中:
                    return 出, 表头
                候选.append((出, 表头))
            else:
                i += 1
        if 候选:
            return 候选[0]
        return [], []

    # ---------- 网格（九宫格 / 四宫格 / 动态 都用）----------

    def 网格们(self):
        """
        收 `## 格N —— 标题` 或 `## 锚点N —— 标题` 底下的字段。
        字段值可以换行续写（缩进 2 空格）。
        """
        出 = []
        i = 0
        while i < len(self.行):
            s = self.行[i]
            m1 = 重标题.match(s)
            m2 = 重锚点标题.match(s)
            if m1 or m2:
                m = m1 or m2
                编号 = int(m.group(1))
                种 = "格" if m1 else "锚点"
                标题行号 = i
                题 = m.group(2).strip()
                字段 = {}
                序 = []
                末 = None
                j = i + 1
                while j < len(self.行):
                    t = self.行[j]
                    if 重标题.match(t) or 重锚点标题.match(t):
                        break
                    if 重任意标题.match(t):
                        break
                    mf = 重字段.match(t)
                    if mf:
                        名 = mf.group(1)
                        值 = mf.group(2).strip()
                        if 名 in 字段:
                            字段[名] = (字段[名] + " " + 值).strip()
                        else:
                            字段[名] = 值
                            序.append(名)
                        末 = 名
                        j += 1
                        continue
                    # 续行：缩进 2 空格以上，且不是空行
                    if 末 and t[:2] == "  " and t.strip():
                        字段[末] = (字段[末] + " " + t.strip()).strip()
                        j += 1
                        continue
                    if not t.strip():
                        末 = None
                        j += 1
                        continue
                    # 别的行（说明文字之类）不算解析失败，跳过
                    末 = None
                    j += 1
                出.append({
                    "种": 种, "编号": 编号, "标题": 题,
                    "行号": 标题行号 + 1, "字段": 字段, "序": 序,
                })
                i = j
            else:
                i += 1
        return 出

    def 小格们(self):
        """
        收 `### 1-2 推进` 底下的字段（动态提示词用）。
        返回 [(锚编号, 格编号, 阶段名, 行号, 字段)]。
        """
        出 = []
        i = 0
        while i < len(self.行):
            m = 重小标题.match(self.行[i])
            if not m:
                i += 1
                continue
            锚, 格, 阶段 = int(m.group(1)), int(m.group(2)), m.group(3)
            字段 = {}
            末 = None
            j = i + 1
            while j < len(self.行):
                t = self.行[j]
                if 重小标题.match(t) or 重标题.match(t) or 重锚点标题.match(t) or 重任意标题.match(t):
                    break
                mf = 重字段.match(t)
                if mf:
                    字段[mf.group(1)] = mf.group(2).strip()
                    末 = mf.group(1)
                    j += 1
                    continue
                if 末 and t[:2] == "  " and t.strip():
                    字段[末] = (字段[末] + " " + t.strip()).strip()
                    j += 1
                    continue
                末 = None
                j += 1
            出.append((锚, 格, 阶段, i + 1, 字段))
            i = j
        return 出


