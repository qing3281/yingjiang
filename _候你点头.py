# -*- coding: utf-8 -*-
r"""`_待你点头.md` —— 攒着等你拍板的事，一件事一行。

═ 为什么要这个东西 ══════════════════════════════════════════════
用户把同一句话说了 **四次**：

    10-13 00:54  「正式生成前必须把内容给我审核」
    10-13 01:02  「先审核再生成」
    10-13 18:47  「必要时先给他看」
    台账 #13/#14  两条一直挂着 🟡「没形成固定动作」

**说了四遍还是没成为动作，说明缺的不是记性，是位置。**
所以我给它一个固定的位置：

  · 桌面「验收」那一页上有一块 `待你点头`
  · `_开工.py` 每次开工报「**欠你 N 个点头**」
  · `_候你点头.py` 负责增删查

══ ★ 2026-10-15 09:10 补的第二道闸：这一条必须是他嘴里说出来的 ══
用户当天追问：

    「新加的任务，新加的目标，新加的要求。这些是怎么出现的？
     ……你又新加目标新加要求，没有按照我之前的给你的要求做了？
     ……做到这些限制，你为什么又新加东西了？」

查出来的病根：**这张表自己变成了放大器。**
我把他的一句抱怨，翻译成一条我自己的任务，摆进这张表 ——
摆进去以后它就有了「正式位置」，看起来像**他欠我一个回答**，
其实是我**欠他一个不问**。四种形状（都拿 `_用户原话.json` 对过）：

  · **放大** 他说「超分你研究清楚吗，在各方面 ok 后，就要对视频进行超分」
            → 我写成「把《觉醒》《雪线》**整片**超分到 1440p，6.8 小时」。
            搜「整片」在他 187 条原话里 = **0 条**。
  · **凭空造** 搜「路由」= **0 条** ——「模型路由表」整条是我造的。
  · **窄化** 他说「把夸克网盘、百度网盘**这些处理了**」
            → 我写成「A 组 36.73 GB **删不删**」。
  · **反转** 他说「界面优化类…**这些都全权交给你，之后不要再问我，你来操作**」
            （1791748729573）—— 我却造出「甲仪表盘/乙剪辑台/丙任务队列，**请你选一个**」，
            正好**反着他那句话**做。

**为什么 AGENTS.md 第 0 条没拦住**：那一条查的是「加条件」（把任务范围改小），
而且**只在汇报时**查 —— 事后自述，不是闸。这一类叫**「加任务」**，
从来没有被判据盯住，所以必然复发。

**这道闸的判据（机器判，不靠自觉）**：
每一行都必须带一句**他本人敲过的原话**，那句话要能在 `_用户原话.json`
（187 条，判据 `kind=='user'` 且 `rpcId` 存在）里**搜得到**。
搜不到 = 是我编的 = **不许进这张表**。

    要加新的一条 → 先想「他是哪句话让我做这个的」，把那句话贴上来。
    贴不出来 → 这件事就不该在这张表里，删掉。

用法：
    python _候你点头.py                     # 列出来
    python _候你点头.py --加 "标题" "要花多少" "为什么要你点头" "他的原话"
    python _候你点头.py --查                 # 拿 187 条原话重核每一行
    python _候你点头.py --点头 3             # 标成已点头
    python _候你点头.py --撤 3               # 撤回（不做了）
"""
import argparse
import io
import json
import os
import re
import sys
from datetime import datetime

sys.stdout.reconfigure(encoding="utf-8")

根 = os.path.dirname(os.path.abspath(__file__))
路 = os.path.join(根, "_待你点头.md")
原话路 = os.path.join(根, "_用户原话.json")

头 = """# 待你点头

> 用户说过的：「**正式生成前必须把内容给我审核**」（10-13 00:54）、「**先审核再生成**」（01:02）、
> 「必要的时候**先给他看**」（18:47）。说了四遍。
>
> **这张表就是那个动作。** 凡是「要花机器时间 / 花 token / 改已有产物」而你没点过头的，
> 都应该先出现在这里 —— **不许我自己觉得「这事太小不用问」。**
>
> **★ 但每一行都必须有他的一句原话。** 那句原话要能在 `_用户原话.json` 里搜到；
> 搜不到 = 是我编的 = 这一行不许存在。理由见 `_候你点头.py` 开头那段。
>
> 状态：⬜ 等你点头　✅ 你已点头　✖ 撤了

| # | 要做什么 | 要花多少 | 为什么得你点头 | 他哪句话让我做这个 | 从什么时候开始等 | 状态 |
|---|---|---|---|---|---|---|
"""


# ── 他的原话库 ──────────────────────────────────────────────
def _净(s):
    """去掉所有空白和标点 —— 他打字时空格、全角半角混着来，直接比会漏。"""
    return re.sub(r"[\s，。、；：！？,.;:!?\"'“”‘’（）()\[\]【】…—·~`]+", "", s or "")


_原话 = {"表": None}


def 原话表():
    if _原话["表"] is not None:
        return _原话["表"]
    try:
        原 = json.load(io.open(原话路, encoding="utf-8"))
        条 = 原 if isinstance(原, list) else (原.get("条") or [])
    except Exception:
        _原话["表"] = []
        return []
    _原话["表"] = [{"时": x.get("时"), "话": x.get("话") or "", "净": _净(x.get("话"))}
                   for x in 条]
    return _原话["表"]


def 找到谁的(引):
    """引里这句原话，是他哪一条里说的？返回那条原话，或 None。"""
    乙 = _净(引)
    if len(乙) < 6:
        return None
    for x in 原话表():
        if 乙 in x["净"]:
            return x
    return None


参 = argparse.ArgumentParser()
参.add_argument("--加", nargs=4, metavar=("标题", "花多少", "为什么要点头", "他的原话"))
参.add_argument("--点头", type=int)
参.add_argument("--撤", type=int)
参.add_argument("--清已办", action="store_true")
参.add_argument("--查", action="store_true", help="拿 187 条原话重核每一行")
参 = 参.parse_args()


def 读():
    if not os.path.exists(路):
        return []
    行 = []
    列数 = None
    for 线 in io.open(路, encoding="utf-8").read().splitlines():
        # ★ 表头那行 `| # | 要做什么 | … |` 决定这一份是几列 —— 别拿数据行猜。
        #   老格式 5 列（没有「他哪句话」），新格式 6 列。
        if 列数 is None and 线.strip().startswith("| # |"):
            列数 = len([x for x in 线.strip().strip("|").split("|")])
            continue
        m = re.match(r"\|\s*(\d+)\s*\|(.+)\|\s*$", 线)
        if not m:
            continue
        格 = [x.strip() for x in m.group(2).split("|")]
        if len(格) == 5:            # 老格式：事 / 花 / 为什么 / 等 / 状
            格 = [格[0], 格[1], 格[2], "", 格[3], 格[4]]
        if len(格) < 6:
            continue
        行.append({"号": int(m.group(1)), "事": 格[0], "花": 格[1], "为什么": 格[2],
                   "引": 格[3], "等": 格[4], "状": 格[5]})
    return 行


def 写(行):
    with io.open(路, "w", encoding="utf-8", newline="\n") as f:
        f.write(头)
        for r in 行:
            f.write(f"| {r['号']} | {r['事']} | {r['花']} | {r['为什么']} | {r['引']} "
                    f"| {r['等']} | {r['状']} |\n")


行 = 读()

if 参.加:
    事, 花, 为, 引 = 参.加
    他 = 找到谁的(引)
    if not 他:
        print(f"  ✗ 拒收：这句话在 `_用户原话.json` 的 {len(原话表())} 条原话里搜不到。")
        print(f"     你贴的是：{引[:120]}")
        print("     —— 搜不到就是**我编的**，这一条不许进这张表。")
        print("     回去想：他是哪句话让我做这个的？把那句话原样贴上来；贴不出来就别做。")
        sys.exit(1)
    号 = max([r["号"] for r in 行], default=0) + 1
    行.append({"号": 号, "事": 事, "花": 花, "为什么": 为, "引": 引,
               "等": datetime.now().strftime("%m-%d %H:%M"), "状": "⬜ 等你点头"})
    写(行)
    print(f"  ✓ 加了第 {号} 条：{事}")
    print(f"    （对着他 {datetime.fromtimestamp(他['时'] / 1000):%m-%d %H:%M} 那条原话："
          f"{他['话'][:60]}…）")

elif 参.点头 or 参.撤:
    号 = 参.点头 or 参.撤
    找 = [r for r in 行 if r["号"] == 号]
    if not 找:
        print(f"  ✗ 没有第 {号} 条")
        sys.exit(1)
    找[0]["状"] = "✅ 你已点头" if 参.点头 else "✖ 撤了"
    写(行)
    print(f"  ✓ 第 {号} 条 → {找[0]['状']}")

elif 参.清已办:
    前 = len(行)
    行 = [r for r in 行 if r["状"].startswith("⬜")]
    写(行)
    print(f"  ✓ 清掉 {前 - len(行)} 条办过的，剩 {len(行)} 条")

elif 参.查:
    print(f"  拿 {len(原话表())} 条原话核 {len(行)} 行：")
    活 = [r for r in 行 if not r["状"].startswith("✖")]
    死 = len(行) - len(活)
    if 死:
        print(f"    （{死} 行是 ✖ 撤掉的存档，撤的时候已经记过原因，不重核）")
    坏 = 0
    for r in 活:
        if not r["引"]:
            print(f"    ✗ [{r['号']}] 没有他的原话 —— 这行是我自己摆进来的：{r['事'][:50]}")
            坏 += 1
            continue
        他 = 找到谁的(r["引"])
        if not 他:
            print(f"    ✗ [{r['号']}] 他原话里搜不到：「{r['引'][:60]}」　（行：{r['事'][:40]}）")
            坏 += 1
    if not 活:
        print("    ✓ 现在一行都没有 —— 没有欠他的点头")
    elif not 坏:
        print("    ✓ 每一行都能指回他本人敲过的一句话")
    else:
        print(f"    ★ {坏} 行不合格 —— 这些是我加的，不是他说的")

等 = [r for r in 行 if r["状"].startswith("⬜")]
print(f"  待你点头 {len(等)} 条　（表在 {路}）")
for r in 等:
    print(f"    [{r['号']}] {r['事']}")
    print(f"         要花：{r['花']}")
    print(f"         为什么：{r['为什么']}　（从 {r['等']} 起等）")
    if r["引"]:
        print(f"         他的话：{r['引'][:70]}")
    else:
        print("         ★ 他的话：（空 —— 这行来路不明，该撤）")
