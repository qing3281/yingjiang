条目 = re.compile(r"^\s*(?:-\s*)?(?:\*\*)?\d{4}-\d{2}-\d{2}")


def 分条(路):
    """把一份经验文件切成「条目」。一条 = 一个 `- 日期 …` 行，或一个 `## ` 小节（到下一个 `## ` 为止）。"""
    行们 = io.open(路, encoding="utf-8").read().splitlines()
    出 = []
    i = 0
    while i < len(行们):
        行 = 行们[i]
        if 条目.match(行):
            出.append((i + 1, 行))
            i += 1
        elif 行.startswith("## "):
            j = i + 1
            while j < len(行们) and not 行们[j].startswith("## "):
                j += 1
            出.append((i + 1, "\n".join(行们[i:j])))
            i = j
        else:
            i += 1
    return 出


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--看", action="store_true", help="只打印，不写 记忆\\模式.md")
    ap.add_argument("--门槛", type=int, default=2, help="命中几条才算模式（默认 2）")
    ap.add_argument("--根", default=根)
    a = ap.parse_args()

    夹 = os.path.join(a.根, "记忆", "经验")
    if not os.path.isdir(夹):
        print(f"  ✗ 没有这个目录：{夹}")
        return 1

    全部 = []           # (文件名, 行号, 正文)
    for f in sorted(os.listdir(夹)):
        if f.endswith(".md"):
            全部 += [(f, n, t) for n, t in 分条(os.path.join(夹, f))]
    print(f"  扫了 {len(全部)} 条经验（{len([f for f in os.listdir(夹) if f.endswith('.md')])} 份文件）")

    # ★ 2026-10-15 08:05 加：**台账也要扫**。
    #   病根：有一条病在 `记忆\经验\` 里一条都没有，却在 `要求台账.md` 里挂了 4 条，
    #   全是 🟡「没形成固定动作」—— 「正式生成前必须把内容给我审核」。
    #   只扫经验库就永远数不出它。**数不出来 = 不合格。**
    #   台账按「行」切：一行 = 一条要求，够用了（台账本来就是一行一条）。
    台路 = os.path.join(a.根, "要求台账.md")
    if os.path.isfile(台路):
        台 = [(f"要求台账.md", n, 行)
              for n, 行 in enumerate(io.open(台路, encoding="utf-8").read().splitlines(), 1)
              if 行.strip().startswith("|")]
        print(f"  扫了 {len(台)} 行台账（{台路}）")
        全部 += 台

    结果 = []
    for 名, 判据, 词们 in 词表:
        中 = []
        for f, n, t in 全部:
            if any(w in t for w in 词们):
                中.append((f, n, t))
        if len(中) >= a.门槛:
            结果.append((名, 判据, 中))
    结果.sort(key=lambda r: -len(r[2]))

    print()
    if not 结果:
        print(f"  ✓ 没有哪一类病犯到 {a.门槛} 次以上")
    for 名, 判据, 中 in 结果:
        print(f"  ★ {名}　—— 犯过 {len(中)} 次")
        print(f"      判据：{判据}")
        for f, n, t in 中[:6]:
            print(f"        · {f}:{n}")
        if len(中) > 6:
            print(f"        · …… 还有 {len(中) - 6} 条")
        print()

    脏 = [r for r in 结果 if len(r[2]) >= 3]
    print(f"  合计：{len(结果)} 类复发，其中 {len(脏)} 类已经犯到 3 次以上（这些该进 AGENTS.md）")

    if a.看:
        return 0

    出 = ["# 模式 —— 犯过两次以上的病",
          "",
          f"> 由 `_找复发.py` 生成（{datetime.now():%Y-%m-%d %H:%M}）。",
          "> **单次是事故，重复才是病。** 这一份只放犯过 ≥2 次的；≥3 次的该往 `AGENTS.md` 里写。",
          "> 手改这份没用，下次生成会覆盖 —— 要改就改 `_找复发.py` 的 `词表`，或在 `记忆\\经验\\` 里补条目。",
          ""]
    for 名, 判据, 中 in 结果:
        出.append(f"## {名}　（{len(中)} 次）")
        出.append("")
        出.append(f"**判据**：{判据}")
        出.append("")
        for f, n, t in 中:
            首 = t.strip().splitlines()[0].strip()
            if len(首) > 200:
                首 = 首[:200] + "…"
            出.append(f"- `{f}:{n}`　{首}")
        出.append("")
    路 = os.path.join(a.根, "记忆", "模式.md")
    io.open(路, "w", encoding="utf-8", newline="\n").write("\n".join(出) + "\n")
    print(f"  ✓ {路}　{os.path.getsize(路):,} B")
    return 0


