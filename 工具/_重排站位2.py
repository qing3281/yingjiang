for f in ("_格数据_上.py", "_格数据_下.py"):
    p = os.path.join(根, f)
    spec = importlib.util.spec_from_file_location("m_"+f[:6], p)
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    n = 0
    头 = io.open(p, encoding="utf-8").read().split("格 = [")[0]
    出 = [头 + "格 = [\n"]
    for g in m.格:
        if g["号"] in 新:
            景, 机, 位, 衣 = 新[g["号"]]
            g = dict(g); g["景"]=景; g["机"]=机; g["位置"]=位; g["衣"]=衣; n += 1
        出.append("dict(号=%d, 场=%r, 秒=%d, 标=%r,\n 目的=%r,\n 景=%r, 机=%r,\n 场号=%r, 衣=%r, 位置=%r,\n 画面=%r,\n 动作=%r,\n 台词=%r, 音=%r, 点=%r),\n\n"
                  % (g["号"],g["场"],g["秒"],g["标"],g["目的"],g["景"],g["机"],g["场号"],str(g["衣"]),g["位置"],g["画面"],g["动作"],g["台词"],g["音"],g["点"]))
    出.append("]\n")
    io.open(p,"w",encoding="utf-8").write("".join(出))
    print("  ✓ %s  改了 %d 格" % (f, n))
