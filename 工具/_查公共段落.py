# -*- coding: utf-8 -*-
"""查「公共段落里混进了不该有的东西」—— 第 1 类病，犯过 20 次。

背景（这一条的来历，别删）：
    用户 m35421 原话：「**龙的犄角又长到楚子航头上了**」。
    病根：`_写作规约.py` 的 `场景["龙巢"]` 末尾**粘着一整段龙的描写**。
    而 `场景` / `场景光` 是**每一格都拼进提示词**的公共段落 ——
    于是 32 格**格格里都趴着一条龙**，龙角自然被画到楚子航头上。

    同一个病在这个工程里犯了不止一次：
      · 场景光里写过「唯一的光是**楚子航手里那支手电筒**」
        → 32 格里 20 多格人人举着手电，且每格都把楚子航叫出来
      · 场景里写过「十二个灯箱里四个还亮着」→ 用户：「废弃地铁站为什么会有灯啊？」

规矩：**`场景` / `场景光` 只描述「这个空间本身」。
      凡是活的（人、龙、手、脸）、凡是能拿的东西（手电、灯、火把），
      一律由这一格自己的【画面】说，不许出现在公共段落里。**

用法：
    python _查公共段落.py                    # 查默认那部戏（楚子航）
    python _查公共段落.py --作品 楚子航
    python _查公共段落.py --文件 <规约.py>     # 查别的戏
"""
import argparse
import importlib.util
import io
import os
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # 工具\ 的上一级 = 工作区根
默认作品 = os.path.join(根, "影匠", "作品", "楚子航", "_写作规约.py")

# ── 不许出现在公共段落里的词 ──────────────────────────────
# 分两类：**活的**和**能拿的**。两类都是「这一格有没有它，得由这一格自己说了算」。
词表 = [
    # 活物 / 身体部件
    ("活物·龙", ["龙", "芬里厄", "鳞", "鳞甲", "膜翼", "翼展", "指骨", "獠牙",
                 "骨刺", "骨板", "骨鳍", "龙角", "黑角", "竖缝眼", "琥珀黄"]),
    ("活物·人", ["楚子航", "夏弥", "路明非", "耶梦加得", "他", "她", "背影",
                 "头发", "眼睛", "脸", "手", "手指", "小腿"]),
    # 能拿的东西 / 会发光的器具
    ("器具·光", ["手电", "手电筒", "灯箱", "应急灯", "火把", "荧光棒", "头灯"]),
    # 身体造成的痕迹（血是角色造成的，不是空间自带的）
    ("痕迹·血", ["伤口", "血", "血泊"]),
]

# ── 白名单：这些词在公共段落里出现是**合理**的 ────────────────
# 每一条都要写清「为什么它可以在这里」。写不出理由的，不许加。
白名单 = {
    "混凝土": "说的是地面材质",
    "水泥": "说的是天花板材质",
    "钢筋": "墙里露出来的建筑结构",
    "卡扣": "凹槽上断掉的金属件，是建筑的一部分",
    "灰": "积在地面上的灰",
    "蛛网": "天花板上的蛛网",
    "裂缝": "地面上的裂缝",
    "钢梁": "斜插在地上的折断钢梁",
    "垃圾桶": "倒下的垃圾桶（空地上的杂物，不是谁拿着的）",
    "凳": "翻过来的塑料凳",
    "报纸": "散在地上的废报纸",
}


def 载入(路):
    """把 _写作规约.py 当模块载进来（不能 import，名字里有中文）。"""
    规范 = importlib.util.spec_from_file_location("规约_被查", 路)
    m = importlib.util.module_from_spec(规范)
    规范.loader.exec_module(m)
    return m


def 找(文, 词):
    """返回这个词在文里出现的位置（去重，同一个词只报一次）。"""
    出 = []
    起 = 0
    while True:
        i = 文.find(词, 起)
        if i < 0:
            break
        出.append(i)
        起 = i + len(词)
    return 出


def 主():
    ap = argparse.ArgumentParser()
    ap.add_argument("--作品", default="楚子航")
    ap.add_argument("--文件", default="")
    a = ap.parse_args()

    路 = a.文件 or (默认作品 if a.作品 == "楚子航"
                    else os.path.join(根, "影匠", "作品", a.作品, "_写作规约.py"))
    if not os.path.exists(路):
        print(f"✗ 找不到 {路}")
        return 2

    m = 载入(路)
    print(f"查 {路}")
    print()

    # 要查的公共段落：凡是从规约里拿到的、名字是「场景/场景光/废弃/公共」开头的 dict，全查
    目标 = []
    for 名 in dir(m):
        if 名.startswith("_"):
            continue
        v = getattr(m, 名)
        if isinstance(v, dict) and any(k in 名 for k in ("场景", "场景光", "废弃", "公共", "光")):
            目标.append((名, v))

    if not 目标:
        print("✗ 规约里没找到任何公共段落 dict")
        return 2

    总问题 = 0
    for 名, d in 目标:
        print(f"══ {名}（{len(d)} 段，每一段都会拼进用到它的每一格）══")
        for 键, 文 in d.items():
            if not isinstance(文, str):
                continue
            命中 = []
            for 类, 词们 in 词表:
                for w in 词们:
                    if w in 白名单:
                        continue
                    if w in 文:
                        命中.append((类, w, 文.count(w)))
            if 命中:
                总问题 += len(命中)
                print(f"  ✗ [{键}] {len(文)} 字 —— 混进了 {len(命中)} 个不该有的词")
                for 类, w, n in 命中:
                    位置 = 找(文, w)
                    头 = max(0, 位置[0] - 18)
                    片 = 文[头:位置[0] + 18 + len(w)].replace("\n", " ")
                    print(f"       {类}  「{w}」×{n}   …{片}…")
            else:
                print(f"  ✓ [{键}] {len(文)} 字 —— 干净")
        print()

    print("─" * 66)
    if 总问题:
        print(f"★ 共 {总问题} 处。公共段落是每一格都拼的 ——")
        print("  上面每一个词，都会出现在用到这一段的所有格里。")
        print()
        print("  怎么改（照这个来，别自己想）：")
        print("    · 是**这一格才有的**东西（龙、某个人的手、一支手电）")
        print("      → 从公共段落里删掉，挪进那一格的【画面】")
        print("    · 是**这一格才有的光**（龙颈伤口的反光、眼球自己发的光）")
        print("      → 从 `场景光` 删掉，挪进那一格的【画面】末尾那个「光只有几处：…」")
        print("    · 是**这个空间本来就有的**（混凝土、天花板、钢梁、裂缝）")
        print("      → 留着不动")
        print()
        print("  ★ 改完**必须重出用到这一段的所有格** —— 光改文字，图不会自己变。")
    else:
        print("✓ 公共段落全都干净：里面没有任何活物、没有能拿的东西。")
    print()
    print("（判据：这一段里的每个词，放到**任意一格**里都成立吗？"
          "不成立的就是漏进来的。）")
    return 1 if 总问题 else 0


if __name__ == "__main__":
    sys.exit(主())
