import io
import os
import re
import shutil
import sys
import time

sys.stdout.reconfigure(encoding="utf-8")

路 = r"D:\DSHworkspace\影匠\作品\雪线\02-九宫格.md"
干跑 = "--看" in sys.argv

改法 = [
    (13,
     "眼睫上的霜簌簌落下一层，紫色瞳孔在冷光里轻微收缩又放开，睫毛眨了一次，贴着脸颊的那缕发丝轻轻浮动",
     "紫色瞳孔先在冷光里缩成一个小点、再慢慢放开占满整个虹膜；上睫毛从上往下降下来盖住瞳孔、"
     "停了半拍又抬起来，睫上那层细霜跟着碎成几粒往下掉；脸颊边那缕银发被风吹得横着飘过去、扫过下颌"),
]

全 = io.open(路, encoding="utf-8").read()
新 = 全
好 = 坏 = 0

for 号, 旧, 新文 in 改法:
    块 = re.search(rf"\n##\s*格{号}\s*——.*?(?=\n##\s*格|\Z)", 新, re.S)
    if not 块:
        print(f"  ✗ 格{号}：找不到这一格")
        坏 += 1
        continue
    t = 块.group(0)
    n = t.count(旧)
    if n != 1:
        print(f"  ✗ 格{号}：旧串在本格里出现 {n} 次（必须恰好 1 次）")
        坏 += 1
        continue
    新 = 新[:块.start()] + t.replace(旧, 新文, 1) + 新[块.end():]
    print(f"  ✓ 格{号}　{len(旧)} 字 → {len(新文)} 字")
    好 += 1

print()
print(f"  {'[干跑] ' if 干跑 else ''}找到 {好} 处，有问题 {坏} 处")
print(f"  {len(全.encode()):,} → {len(新.encode()):,} B")

if 坏:
    print("  ✗ 有问题就不写，先修")
    sys.exit(1)
if 干跑:
    sys.exit(0)

备 = os.path.join(r"D:\DSHworkspace\影匠\作品\雪线",
                  f"_bak_九宫格_改动作3前_{time.strftime('%Y%m%d-%H%M%S')}.md")
shutil.copy2(路, 备)
io.open(路, "w", encoding="utf-8", newline="\n").write(新)
print(f"  ✓ 备份 {备}")
print(f"  ✓ 已写 {路}")
