# -*- coding: utf-8 -*-
"""最后两条告警：**字段名太长**。

`_字段行 = ^-\s*([^:：]{1,12}?)\s*[:：]` —— 冒号前面**最多 12 个字**。
`耶梦加得（她的龙形态，只在第 6 格的影子里出现）` 有 24 个字，整行匹配不上，
退到「裸字段行」（也是 12 字上限）还是匹配不上 → 报「没人认领」。

改法：把括号里的注解挪到冒号后面，字段名压到 12 字以内。
"""
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")
p = r"D:\DSHworkspace\影匠\作品\楚子航\02-九宫格.md"
文 = open(p, encoding="utf-8").read()

对 = [
    ("- 耶梦加得（她的龙形态，只在第 6 格的影子里出现）：",
     "- 耶梦加得："),
    ("- **全片没有一个「俯拍」**：",
     "- 机位规矩："),
]
for 旧, 新 in 对:
    if 旧 in 文:
        文 = 文.replace(旧, 新)
        print("  ✓ %s  →  %s" % (旧[:26], 新))

# 把被摘掉的注解补回句子里，别丢信息
文 = 文.replace("- 耶梦加得：一条通体黑色的蛇形巨龙",
                "- 耶梦加得（她的龙形态，只在第 6 格的影子里出现）：一条通体黑色的蛇形巨龙")
文 = 文.replace("- 机位规矩：所有机位都是 eye level，除非该格明写",
                "- 机位规矩：**全片没有一个「俯拍」**，所有机位都是 eye level，除非该格明写")
open(p, "w", encoding="utf-8").write(文)
print("  →", p)
