# -*- coding: utf-8 -*-
"""查「无名指代」—— 用「那个背影 / 一个后脑勺 / 那个人」去指一个角色，而不点名。

来历（别删，这是判据的出处）：
    用户提过 **5 次**，最近两次原话：
      · 「格19 那个背影怎么是夏弥的头发」—— 那一格里写的是
        「画面左边**那个背影**的右臂正慢慢放下来」，模型不知道那是谁，
        就给它安了一个夏弥的浅棕长发 + 蓝蝴蝶结。
      · 「格23 有两个楚子航」「格30 又多了一个夏弥出来」—— 同一个病：
        文字里出现了一个**没有名字的人形**，模型只好自己造一个，
        造出来的就多一个人。

为什么必须点名：
    文生图模型**不认识代词**。「他/她/那个背影」在它眼里不是一个指代，
    是一个**新的、没有约束的人形**。要它画谁，就写谁的名字 + 衣着特征。

两种形状（都要查）：
    ① **无名的指代**：「那个背影」「一个后脑勺」「那个人」
    ② **重复命名**：【位置】里点了名，【画面】里又用「一个女孩」说一遍 →
       模型当成两个人，于是画出两个。

用法：
    python _查无名指代.py                # 查楚子航
    python _查无名指代.py --作品 <名>
"""
import argparse
import importlib.util
import os
import re
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # 工具\ 的上一级 = 工作区根

# ① 不给名字的人形说法。★ 这一行就是判据本身 —— 以后想到新的就往这儿加。
无名说法 = [
    "那个背影", "一个背影", "一道背影",
    "那个后脑勺", "一个后脑勺",
    "那个人", "有个人", "那人",
    "那个身影", "一个身影",
    "那个男的", "那个女的", "一个男人", "一个女人",
    "对方", "另一个人",
    # ★ 2026-10-16 02:30 补的 —— 上一版漏了「裸人形词」。
    #   漏的例子：
    #     · 格21 提示词里同时有「那个悬在半空的**女孩**」和「**夏弥**」，
    #       模型当成两个人，**画了两个夏弥**（左边浅棕发带黑角、右边银白发蓝蝴蝶结）。
    #     · 格22 里「左边那个**青年**」其实就是楚子航，模型照样另造一个。
    #   这一类比「那个背影」更隐蔽 —— 因为**它读起来就像在说某个人**，
    #   而模型不认识"指的是谁"，它只认识"又出现了一个人形"。
    "女孩", "男孩", "青年", "少年", "少女", "女生", "男生",
    "男人", "女人", "男子", "女子", "人影", "人形",
]

# ② 无名的「一个X」——【位置】里点了名时，画面里再说一遍就是两个人
一个说法 = ["一个女孩", "一个男生", "一个男人", "一个女人", "一个少年",
            "一个女生", "一个身影", "一个人", "那个女孩", "那个男生"]

# 名字。★ 同一个工程里所有角色都要在这儿 —— 少一个就会误报。
名字们 = ["楚子航", "夏弥", "路明非", "耶梦加得", "芬里厄"]

# 这些说法虽然像人形，但说的是**没有人**，放过。
不算 = [
    r"画面里没有人", r"画面里没有一个人", r"没有人的任何部位", r"一个人都没有", r"一个人也没有",
    r"只有这两个人", r"只有他一个人", r"只有她一个人", r"看不到一个人",
    r"两个背影", r"两个人影", r"人影、只有画面高度", r"人只占画面",
]


def 载入(路, 名):
    sp = importlib.util.spec_from_file_location(名, 路)
    m = importlib.util.module_from_spec(sp)
    sp.loader.exec_module(m)
    return m


def 过(片):
    return any(re.search(p, 片) for p in 不算)


def 查一格(g):
    出 = []
    # ① 无名的指代
    for 字段 in ("位置", "画面", "动作", "特效", "点", "目的", "标"):
        文 = g.get(字段, "")
        if not isinstance(文, str) or not 文:
            continue
        for w in 无名说法:
            起 = 0
            while True:
                i = 文.find(w, 起)
                if i < 0:
                    break
                起 = i + len(w)
                片 = 文[max(0, i - 30): i + 30 + len(w)]
                if 过(片):
                    continue
                # ★ 真判据：**前后 40 字内有没有出现角色的名字**。
                #   有名字 → 说清了是谁；没名字 → 模型会自己造一个人出来。
                窗口 = 文[max(0, i - 40): i + 40 + len(w)]
                if any(n in 窗口 for n in 名字们):
                    continue
                出.append((字段, w, 片.replace("\n", " ")))
    # ② 位置里点了名、画面里又用一个「一个X」
    位置名 = [n for n in 名字们 if n in g.get("位置", "")]
    画面 = g.get("画面", "")
    if 位置名:
        for w in 一个说法:
            起 = 0
            while True:
                i = 画面.find(w, 起)
                if i < 0:
                    break
                起 = i + len(w)
                片 = 画面[max(0, i - 30): i + 30 + len(w)]
                if 过(片):
                    continue
                窗口 = 画面[max(0, i - 40): i + 40 + len(w)]
                if any(n in 窗口 for n in 名字们):
                    continue
                出.append(("画面·与位置重复", w, 片.replace("\n", " ")))
    return 出


def 主():
    ap = argparse.ArgumentParser()
    ap.add_argument("--作品", default="楚子航")
    a = ap.parse_args()
    目 = os.path.join(根, "影匠", "作品", a.作品)

    格们 = []
    for f in ("_格数据_上.py", "_格数据_下.py"):
        路 = os.path.join(目, f)
        if os.path.isfile(路):
            格们 += 载入(路, "数据_" + f[-6:-3]).格
    格们.sort(key=lambda g: g["号"])

    print(f"查《{a.作品}》　{len(格们)} 格")
    print("判据：一段里出现人形说法，而它前后 40 字内没有任何角色的名字 → 报出来")
    print()
    总 = 0
    坏格 = []
    for g in 格们:
        问题 = 查一格(g)
        if 问题:
            总 += len(问题)
            坏格.append(g["号"])
            print(f"  ✗ 格{g['号']:>2}　{g.get('标','')[:26]}　{len(问题)} 处")
            for 字段, w, 片 in 问题:
                print(f"       [{字段}] 「{w}」　…{片}…")
    if not 总:
        print(f"  ✓ {len(格们)} 格里没有任何无名的人形 —— 每一处都点了名。")
    print()
    print("─" * 66)
    if 总:
        print(f"★ 共 {总} 处，在格 {坏格}。")
        print()
        print("  怎么改：把「那个背影」换成「<名字>的<部位>」，并且补一句它穿什么。")
        print("    反例：「画面左边那个背影的右臂正慢慢放下来」")
        print("    正例：「画面左下角楚子航那半条左臂正慢慢放下来」")
        print()
        print("  ★ 改完**必须重出这些格** —— 文字改了图不会自己变。")
    else:
        print("✓ 全过。")
    return 1 if 总 else 0


if __name__ == "__main__":
    sys.exit(主())
