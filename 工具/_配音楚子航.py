def 补映射(干: bool):
    d = json.load(open(映射路, encoding="utf-8"))
    旧 = sorted(d.get("角色", {}).keys())
    新 = [k for k in 新角色 if k not in d["角色"]]
    print(f"  映射表现有 {len(旧)} 个角色：{'、'.join(旧)}")
    print(f"  要新增 {len(新)} 个：{'、'.join(新) if 新 else '（都已经在表里了）'}")
    if not 新:
        return 0
    if 干:
        print("  （--只看：一个字都没落盘）")
        return len(新)
    备份 = 映射路 + time.strftime(".bak-%Y%m%d-%H%M%S")
    shutil.copy2(映射路, 备份)                       # ★ 带文件名，不是带目录
    assert os.path.isfile(备份) and os.path.getsize(备份) == os.path.getsize(映射路)
    for k in 新:
        d["角色"][k] = 新角色[k]
    with open(映射路, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
    回 = json.load(open(映射路, encoding="utf-8"))
    print(f"  ✓ 备份 {os.path.basename(备份)}（{os.path.getsize(备份)} B）")
    print(f"  ✓ 写完 {len(回['角色'])} 个角色（{len(旧)} → {len(回['角色'])}），"
          f"新增的都读得回来：{all(k in 回['角色'] for k in 新)}")
    return len(新)


def 配(干: bool):
    import 配音
    import _台词表
    if 干:
        print(f"  将要配 {len(_台词表.台词表)} 句：")
        for 号 in sorted(_台词表.台词表):
            谁, 词, 源 = _台词表.台词表[号]
            print(f"    格%-3d %-6s %-4s %s" % (号, 谁, 源, 词))
        print(f"  一格 {_台词表.一格秒:.4f} 秒　全片 {32 * _台词表.一格秒:.2f} 秒 = "
              f"{32 * _台词表.一格秒 / 60:.2f} 分")
        print("  （--只看：没连 ComfyUI、没花钱）")
        return 0
    表 = [{"序号": 号, "角色": 谁, "台词": 词}
          for 号, (谁, 词, 源) in sorted(_台词表.台词表.items()) if 词]
    print(f"  真配 {len(表)} 句 → {配音输出}")
    t0 = time.time()
    果 = 配音.批量(表, 输出目录=配音输出, 报=lambda s: print("   ", s))
    好 = [x for x in 果["配音"] if x["路"]]
    坏 = [x for x in 果["配音"] if not x["路"]]
    print(f"\n  ✓ {len(好)}/{len(表)} 句配出来了　总时长 {果['总时长']} 秒　"
          f"用时 {time.time() - t0:.0f} 秒 = {(time.time() - t0) / 60:.1f} 分")
    print(f"  角色解析：{json.dumps(果['角色解析'], ensure_ascii=False)}")
    for x in 坏:
        print(f"     ✗ 格{x['序号']} {x.get('角色')}：{x['错']}")
    # 写一张对照表，后面接片/做字幕都从这张表走（格号 → 音频路径 + 秒数）
    表路 = os.path.join(配音输出, "_配音表.json")
    with open(表路, "w", encoding="utf-8") as f:
        json.dump(果, f, ensure_ascii=False, indent=2)
    print(f"  ✓ 对照表 {表路}（{os.path.getsize(表路)} B）")
    return 0 if not 坏 else 1


