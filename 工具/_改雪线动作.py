r"""★ 《雪线》的真因不是提示词 —— 是 **`动作` 字段自己就写着「不动」**。

量的结果（`_量动作语气.py 雪线`，去噪口径）：

| 组 | 格数 | 运动量中位 | <0.2 的比例 |
|---|---|---|---|
| 甲 动作里写着「停住 / 不动 / 没有变」 | 20 | **0.168** | **65%** |
| 乙 只有「微微 / 极缓慢」 | 11 | 0.283 | 27% |
| 丙 动作里没有减速词 | 14 | **0.956** | **7%** |

**甲和丙差 5.7 倍。** 而且顺手否掉了另一个猜想：这**不是景别偏置** ——
《雪线》的特写 47% 冻住，全景 0% 冻住；《觉醒》的大远景反而最活跃（中位 0.845）。
所以「运动量」这个尺子跨景别仍然是可比的。

**做法**：只改 `动作` 字段，把它从「别动」改成「真的动起来」。
`提示词`（首帧长什么样）**一个字不动** —— 因为《雪线》的提示词没病，
病在动作描述上。

用法：python _改雪线动作.py --看     （干跑）
      python _改雪线动作.py           （真改，自动备份）
"""
import io
import os
import re
import shutil
import sys
import time

sys.stdout.reconfigure(encoding="utf-8")

路 = r"D:\DSHworkspace\影匠\作品\雪线\02-九宫格.md"
干跑 = "--看" in sys.argv

改法 = [
    (34, "两个点面对面立在画面中央，风把四周的雪面吹出极缓慢的波纹，两人脚下的乱痕边缘一点点变软",
         "画面正中那两个身影之间开始有动作：右边那个朝左边跨出一步、长袍下摆把脚前的雪扫开一片，"
         "左边那个的肩膀往后让了半寸、脚跟跟着挪了一下，两人脚下的乱痕上被踩出几道新的脚印"),
    (9, "那个小黑点在脚印尽头停下，风把周围的雪面吹出极缓慢的流动，脚印的坑边缘一点点变软",
        "那个小黑点顺着脚印一路往画面这边走，走到脚印尽头又连着迈了两步，"
        "每一步都在雪面上踩出一圈新的坑，身形从针尖大的一点慢慢长到能看出是一个人在走"),
    (17, "她肩头的云纹刺绣被风吹得翻了边，长发在画面左缘飘动，远处那个针尖大的黑点几乎不动，她的眼睛没有离开",
         "远处地平线上那个针尖大的黑点一点一点变大、整个身子朝画面这边移过来；"
         "她的下颌跟着抬高了一截，画面左缘那片长发被风整片掀起来又落回去"),
    (11, "她嘴唇微微张开又合上，一小团白气从唇边散开被风扯平，胸口的云纹刺绣被风压了一下，其余不动",
         "她开口说话：嘴唇张开、喉咙动了几下，白气一连吐出三口、一口比一口长；"
         "说完之后她整个人往前迈出一步，长袍下摆在雪面上扫出一道弧"),
    (14, "风贴着地面把雪吹成薄薄的一层在动，那个极小的黑点几乎不动、只在原位上轻微地颤，凌霜的身影在画面右三分之一处站定",
         "雪面上那个极小的黑点开始往画面这边移动，每走一步身后就多一个脚印，"
         "身形从一个小点渐渐长成一个看得出轮廓的人；凌霜在画面右三分之一处把右手按上剑柄、重心往后挪了半步"),
    (41, "那张脸连一丝颤动都没有，睫毛眨了一次，唇角平直的线没有变，发丝与肩头的细雪一点点化开，画面下缘的剑尖悬着不动",
         "那张脸朝剑尖的方向低了半寸，喉咙上下动了一下，睫毛连着眨了两回，"
         "肩头那层细雪随着这个动作整片滑落下去；画面下缘那截剑尖跟着往上抬了一小段"),
]

全 = io.open(路, encoding="utf-8").read()
新 = 全
好 = 0
坏 = 0
for 号, 旧, 新文 in 改法:
    块 = re.search(rf"\n##\s*格{号}\s*——.*?(?=\n##\s*格\d+\s*——|\Z)", 新, re.S)
    if not 块:
        print(f"  ✗ 格{号}：找不到这一格")
        坏 += 1
        continue
    t = 块.group(0)
    n = t.count(旧)
    if n != 1:
        print(f"  ✗ 格{号}：旧串在本格里出现 {n} 次（必须恰好 1 次）")
        坏 += 1
        continue
    新 = 新[:块.start()] + t.replace(旧, 新文, 1) + 新[块.end():]
    print(f"  ✓ 格{号}　{len(旧)} 字 → {len(新文)} 字")
    好 += 1

print()
print(f"  {'[干跑] ' if 干跑 else ''}找到 {好} 处，有问题 {坏} 处")
print(f"  {len(全.encode()):,} → {len(新.encode()):,} B")

if 坏:
    print("  ✗ 有问题就不写，先修")
    sys.exit(1)
if 干跑:
    sys.exit(0)

备 = os.path.join(r"D:\DSHworkspace\影匠\作品\雪线",
                  f"_bak_九宫格_改动作前_{time.strftime('%Y%m%d-%H%M%S')}.md")
shutil.copy2(路, 备)
io.open(路, "w", encoding="utf-8", newline="\n").write(新)
print(f"  ✓ 备份 {备}")
print(f"  ✓ 已写 {路}")
