with open(经验, "a", encoding="utf-8") as f:
    f.write("\n".join(段) + "\n")

后 = os.path.getsize(经验)
print("✓ %s" % 经验)
print("  %d → %d 字节（+%d）　备份 %s" % (前, 后, 后 - 前, os.path.basename(备份)))
