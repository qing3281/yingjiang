if not os.path.isfile(经验):
    print("✗ 找不到 %s" % 经验)
    raise SystemExit(1)

前 = os.path.getsize(经验)
备份 = 经验 + ".bak-" + time.strftime("%Y%m%d-%H%M%S")
shutil.copy2(经验, 备份)

段 = ["\n## 交接与整理（2026-10-16 补）\n"]
