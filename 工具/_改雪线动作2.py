    块 = re.search(rf"\n##\s*格{号}\s*——.*?(?=\n##\s*格\d+\s*——|\Z)", 新, re.S)
    if not 块:
        print(f"  ✗ 格{号}：找不到这一格")
        坏 += 1
        continue
    t = 块.group(0)
    n = t.count(旧)
    if n != 1:
        print(f"  ✗ 格{号}：旧串在本格里出现 {n} 次（必须恰好 1 次）")
        坏 += 1
        continue
    新 = 新[:块.start()] + t.replace(旧, 新文, 1) + 新[块.end():]
    print(f"  ✓ 格{号}　{len(旧)} 字 → {len(新文)} 字")
    好 += 1

