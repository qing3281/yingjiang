def 人(n):
    for u in ("B", "K", "M", "G"):
        if n < 1024:
            return "%.1f%s" % (n, u)
        n /= 1024.0
    return "%.1fP" % n


def 扫一(底):
    n = 0
    z = 0
    for _b, _d, fs in os.walk(底):
        for f in fs:
            p = os.path.join(_b, f)
            if os.path.isfile(p):
                n += 1
                z += os.path.getsize(p)
    return n, z


